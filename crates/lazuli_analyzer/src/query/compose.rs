//! `query.compose` W2 — analyzer lowering for the declarative composite read.
//!
//! Lifts a parsed [`syntax::ComposeQueryDecl`] onto the resolved
//! [`ir::ComposeQuery`] that Go codegen (W5) consumes — the W2→W5 contract.
//! See `docs/proposals/ir-composite-read-primitive-2026-05-29.md` §5.
//!
//! ## What W2 resolves (vs. defers to doctor/W3)
//!
//! * Root + FK-path JOIN edges, projection sources, and the closed-catalog
//!   subselects are resolved against the IN-FEATURE relation graph here.
//! * Cross-feature roots / FK hops that leave the feature are TRUSTED at
//!   lowering and validated by doctor with Module context — the same
//!   deferral the owner-scope synth uses (`conventions/owner_scope.rs`).
//! * Structurally-detectable malformations surface as clean
//!   [`AnalyzeError`]s (never panics), giving the W3 doctor codes
//!   (`COMPOSE-JOIN-PATH-001` / `-PROJECTION-SOURCE-001` /
//!   `-SUBSELECT-RELATION-001`) their data.
//!
//! ## Scope inheritance (the verifiability-critical part)
//!
//! The tenant + soft-delete predicate is GENERATED by codegen from
//! `effective_tenancy` on the root, exactly like [`ir::ListQuery`]. The
//! analyzer records the ORIGIN ([`ir::ComposeScopeOrigin`]) so inspect (W6)
//! and doctor (W3) can prove the predicate is present without reading a
//! handler — `Inherited` by default (secure), `Overridden` only when the
//! author wrote `scope override` (§5.2 / §5.3).
//!
//! Predicate / order / key clause lifting lives in the sibling
//! [`super::compose_predicates`] module.


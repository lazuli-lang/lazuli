//! Mobile-target runtime emitter. Single-file output:
//! `dist/ts-mobile/runtime/layout.tsx` per
//! `docs/proposals/mobile-target.md` §5.4. The body wires Expo Router's
//! `<Stack />` inside `<QueryClientProvider>` inside `<LazuliProvider>`
//! using the user-owned `frontends/mobile/shell/client.ts`.
//!
//! The user-owned `frontends/mobile/app/_layout.tsx` is a one-line
//! re-export of this file (scaffolded once in cell B.2). Regenerating
//! always rewrites this file; user customization happens at the
//! wrapper layer.

/// Canonical layout body for the Expo Router app root. Deterministic
/// — no project-specific substitution today. Future iterations may
/// inject app-name or theme provider tokens if a real pilot needs them.
pub const MOBILE_RUNTIME_LAYOUT_TSX: &str = r#"// Code generated by lazuli; DO NOT EDIT.
import { Stack } from "expo-router";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { LazuliProvider } from "@lazuli/runtime/react";
import { client } from "../../../frontends/mobile/shell/client";

const queryClient = new QueryClient();

export default function RootLayout() {
  return (
    <LazuliProvider client={client}>
      <QueryClientProvider client={queryClient}>
        <Stack />
      </QueryClientProvider>
    </LazuliProvider>
  );
}
"#;

/// Emit the mobile runtime layout body. The file path is fixed at
/// `dist/ts-mobile/runtime/layout.tsx`; callers append it to the file
/// list when the module has at least one mobile-target frontend.
///
/// ## Examples
///
/// ```
/// use lazuli_codegen_ts::mobile_runtime::emit_mobile_runtime_layout;
/// let src = emit_mobile_runtime_layout();
/// assert!(src.contains("export"));
/// ```
pub fn emit_mobile_runtime_layout() -> String {
    MOBILE_RUNTIME_LAYOUT_TSX.to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layout_imports_expo_router_stack() {
        let body = emit_mobile_runtime_layout();
        assert!(body.contains(r#"import { Stack } from "expo-router""#));
    }

    #[test]
    fn layout_imports_lazuli_provider_from_runtime_react() {
        let body = emit_mobile_runtime_layout();
        assert!(body.contains(r#"import { LazuliProvider } from "@lazuli/runtime/react""#));
    }

    #[test]
    fn layout_imports_client_via_relative_path() {
        // The layout file lives at `dist/ts-mobile/runtime/layout.tsx`;
        // the shell client lives at `frontends/mobile/shell/client.ts`.
        // Relative path is `../../../frontends/mobile/shell/client`.
        let body = emit_mobile_runtime_layout();
        assert!(body.contains(r#"from "../../../frontends/mobile/shell/client""#));
    }

    #[test]
    fn layout_has_do_not_edit_banner() {
        let body = emit_mobile_runtime_layout();
        assert!(body.starts_with("// Code generated by lazuli; DO NOT EDIT."));
    }

    #[test]
    fn layout_wraps_stack_inside_query_and_lazuli_providers() {
        let body = emit_mobile_runtime_layout();
        let lazuli_idx = body.find("<LazuliProvider").expect("LazuliProvider opens");
        let query_idx = body
            .find("<QueryClientProvider")
            .expect("QueryClientProvider opens");
        let stack_idx = body.find("<Stack").expect("Stack");
        // Lazuli wraps Query wraps Stack.
        assert!(lazuli_idx < query_idx);
        assert!(query_idx < stack_idx);
    }
}

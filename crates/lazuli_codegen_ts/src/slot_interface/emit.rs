//! Slot-interface emission helpers — TypeScript writers for the three
//! emission modes (cell, section, unresolved). Pulled out of `mod.rs`
//! so the dispatcher stays small.

use std::fmt::Write;

use lazuli_codegen_spec::RuntimeFeature;

use super::{FieldBinding, SectionBinding};
use crate::lzx_audience_slot::pascal_case;

pub(super) fn emit_cell_slot(
    slot_name: &str,
    interface_name: &str,
    resource_pascal: &str,
    feature: &RuntimeFeature,
    field_bindings: &[FieldBinding],
    section_bindings: &[SectionBinding],
) -> String {
    let primary = &field_bindings[0];
    let resource_known = feature_has_resource(feature);
    let import_module = format!("../{}.gen.js", feature.name);

    let mut s = String::new();
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(s, "//").ok();
    writeln!(
        s,
        "// Slot: @client.{slot_name} — implement at \
         features/{feature}/<target>/cells/{slot_name}.tsx",
        feature = feature.name
    )
    .ok();
    writeln!(s).ok();

    if resource_known {
        writeln!(
            s,
            "import type {{ {resource_pascal} }} from \"{import_module}\";"
        )
        .ok();
        writeln!(s).ok();
    } else {
        writeln!(
            s,
            "// TODO: source resource `{resource_pascal}` is not in feature `{}`'s \
             resource list; falling back to `unknown`.",
            feature.name
        )
        .ok();
        writeln!(s).ok();
    }

    // Multi-binding comment block — listed before the interface so
    // human reviewers see the divergence above the chosen shape.
    if field_bindings.len() > 1 {
        writeln!(s, "// Bound in {} views:", field_bindings.len()).ok();
        for (idx, binding) in field_bindings.iter().enumerate() {
            let marker = if idx == 0 { "primary" } else { "also" };
            writeln!(
                s,
                "//   - {audience}/{view} field `{field}` ({marker})",
                audience = binding.audience,
                view = binding.view,
                field = binding.field,
                marker = marker
            )
            .ok();
        }
        writeln!(
            s,
            "// v0 picks the first binding's type as the slot contract;"
        )
        .ok();
        writeln!(
            s,
            "// alternative bindings must be cell-shape compatible at use site."
        )
        .ok();
        writeln!(s).ok();
    }

    // Section co-binding (rare but possible) — flag it so the user
    // knows the slot is overloaded between cell and section meanings.
    for section in section_bindings {
        writeln!(
            s,
            "// Also bound as section in {audience}/{view}; this emitter \
             treats the cell binding as authoritative.",
            audience = section.audience,
            view = section.view,
        )
        .ok();
    }
    if !section_bindings.is_empty() {
        writeln!(s).ok();
    }

    writeln!(s, "export interface {interface_name} {{").ok();
    if resource_known {
        writeln!(
            s,
            "  value: {resource_pascal}[\"{field}\"];",
            field = primary.field
        )
        .ok();
        writeln!(s, "  row: {resource_pascal};").ok();
    } else {
        writeln!(s, "  value: unknown;").ok();
        writeln!(s, "  row: unknown;").ok();
    }
    writeln!(s, "}}").ok();
    s
}

pub(super) fn emit_section_slot(
    slot_name: &str,
    interface_name: &str,
    resource_pascal: &str,
    feature: &RuntimeFeature,
    section_bindings: &[SectionBinding],
) -> String {
    let resource_known = feature_has_resource(feature);
    let import_module = format!("../{}.gen.js", feature.name);

    let mut s = String::new();
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(s, "//").ok();
    writeln!(
        s,
        "// Section slot: @client.{slot_name} — receives the whole row, not a \
         single field."
    )
    .ok();
    writeln!(
        s,
        "// Implement at features/{feature}/<target>/cells/{slot_name}.tsx",
        feature = feature.name
    )
    .ok();
    writeln!(s).ok();

    if resource_known {
        writeln!(
            s,
            "import type {{ {resource_pascal} }} from \"{import_module}\";"
        )
        .ok();
        writeln!(s).ok();
    } else {
        writeln!(
            s,
            "// TODO: source resource `{resource_pascal}` is not in feature `{}`'s \
             resource list; falling back to `unknown`.",
            feature.name
        )
        .ok();
        writeln!(s).ok();
    }

    if section_bindings.len() > 1 {
        writeln!(
            s,
            "// Bound as section in {} views:",
            section_bindings.len()
        )
        .ok();
        for binding in section_bindings {
            writeln!(
                s,
                "//   - {audience}/{view}",
                audience = binding.audience,
                view = binding.view,
            )
            .ok();
        }
        writeln!(s).ok();
    }

    writeln!(s, "export interface {interface_name} {{").ok();
    writeln!(s, "  value: void;").ok();
    if resource_known {
        writeln!(s, "  row: {resource_pascal};").ok();
    } else {
        writeln!(s, "  row: unknown;").ok();
    }
    writeln!(s, "}}").ok();
    s
}

pub(super) fn emit_unresolved_slot(slot_name: &str, interface_name: &str) -> String {
    let mut s = String::new();
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(s, "//").ok();
    writeln!(
        s,
        "// TODO: slot @client.{slot_name} has no `cells` or section binding \
         in any view"
    )
    .ok();
    writeln!(
        s,
        "// of this surface. Emitted with `unknown`-typed props so the user's \
         cell.tsx"
    )
    .ok();
    writeln!(
        s,
        "// can still typecheck while the binding is wired up. Add `cells \
         <field>"
    )
    .ok();
    writeln!(
        s,
        "// @client.{slot_name}` to a view or remove the cell file."
    )
    .ok();
    writeln!(s).ok();
    writeln!(s, "export interface {interface_name} {{").ok();
    writeln!(s, "  value: unknown;").ok();
    writeln!(s, "  row: unknown;").ok();
    writeln!(s, "}}").ok();
    s
}

/// Resolve whether the feature carries at least one resource whose
/// PascalCase matches the feature name. The runtime spec emits the
/// resource interface using `pascal_case(feature.name)` as the
/// type identifier; absent a matching resource we cannot type-import.
fn feature_has_resource(feature: &RuntimeFeature) -> bool {
    let target = pascal_case(&feature.name);
    feature
        .resources
        .iter()
        .any(|r| pascal_case(&r.name) == target)
}

//! `tokens.ts` emitter — typed `const tokens = {...} as const` + per-group
//! type aliases. See `docs/proposals/design-tokens.md` §4.2.
//!
//! Color shape detection (§4.2 lines 332-345 of the proposal):
//! - Single `Base` state, no `dark` →   `success: "#16a34a"`.
//! - Multi-state, no `dark` anywhere →  `primary: { base: "...", hover: "...", ... }`.
//! - Any `dark` set on any state →      `background: { base: { light: "#fff", dark: "#000" }, muted: ... }`.
//!
//! The detection is per-token-local (one `ColorToken` is one of the three
//! shapes), so a catalog can mix shapes freely — e.g. `primary` multi-state
//! and `success` single-flat coexist.

use std::fmt::Write;

use super::ir::{ColorStateKind, ColorToken, Design};

/// Emit `dist/ts-web/design/tokens.ts` for the given `Design` catalog.
pub fn emit_tokens_ts(design: &Design) -> String {
    let mut s = String::new();
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(
        s,
        "// Source: design.lzi (design `{}`)",
        design.name
    )
    .ok();
    writeln!(s).ok();
    writeln!(s, "export const tokens = {{").ok();

    // color
    writeln!(s, "  color: {{").ok();
    for color in &design.colors {
        emit_color(&mut s, color);
    }
    writeln!(s, "  }},").ok();

    // typography
    writeln!(s, "  typography: {{").ok();
    writeln!(s, "    family: {{").ok();
    for fam in &design.typography.families {
        writeln!(s, "      {}: {},", quote_key(&fam.name), ts_string(&fam.value)).ok();
    }
    writeln!(s, "    }},").ok();

    writeln!(s, "    scale: {{").ok();
    for entry in &design.typography.scale {
        writeln!(
            s,
            "      {}: {{ size: {}, lineHeight: {} }},",
            quote_key(&entry.name),
            ts_string(&entry.size),
            ts_string(&entry.line_height),
        )
        .ok();
    }
    writeln!(s, "    }},").ok();

    writeln!(s, "    weight: {{").ok();
    for w in &design.typography.weights {
        writeln!(s, "      {}: {},", quote_key(&w.name), w.value).ok();
    }
    writeln!(s, "    }},").ok();

    writeln!(s, "    tracking: {{").ok();
    for t in &design.typography.tracking {
        writeln!(s, "      {}: {},", quote_key(&t.name), ts_string(&t.value)).ok();
    }
    writeln!(s, "    }},").ok();
    writeln!(s, "  }},").ok();

    // space
    writeln!(s, "  space: {{").ok();
    for tok in &design.spaces {
        writeln!(s, "    {}: {},", quote_key(&tok.name), ts_string(&tok.value)).ok();
    }
    writeln!(s, "  }},").ok();

    // radius
    writeln!(s, "  radius: {{").ok();
    for tok in &design.radii {
        writeln!(s, "    {}: {},", quote_key(&tok.name), ts_string(&tok.value)).ok();
    }
    writeln!(s, "  }},").ok();

    // shadow
    writeln!(s, "  shadow: {{").ok();
    for tok in &design.shadows {
        writeln!(s, "    {}: {},", quote_key(&tok.name), ts_string(&tok.value)).ok();
    }
    writeln!(s, "  }},").ok();

    // motion
    writeln!(s, "  motion: {{").ok();
    writeln!(s, "    duration: {{").ok();
    for d in &design.motion.durations {
        writeln!(s, "      {}: {},", quote_key(&d.name), ts_string(&d.value)).ok();
    }
    writeln!(s, "    }},").ok();
    writeln!(s, "    easing: {{").ok();
    for e in &design.motion.easings {
        writeln!(s, "      {}: {},", quote_key(&e.name), ts_string(&e.value)).ok();
    }
    writeln!(s, "    }},").ok();
    writeln!(s, "  }},").ok();

    // breakpoint
    writeln!(s, "  breakpoint: {{").ok();
    for tok in &design.breakpoints {
        writeln!(s, "    {}: {},", quote_key(&tok.name), ts_string(&tok.value)).ok();
    }
    writeln!(s, "  }},").ok();

    // z
    writeln!(s, "  z: {{").ok();
    for tok in &design.z_indices {
        writeln!(s, "    {}: {},", quote_key(&tok.name), tok.value).ok();
    }
    writeln!(s, "  }},").ok();

    writeln!(s, "}} as const;").ok();
    writeln!(s).ok();

    // type aliases
    writeln!(s, "export type ColorToken = keyof typeof tokens.color;").ok();
    writeln!(s, "export type SpaceToken = keyof typeof tokens.space;").ok();
    writeln!(s, "export type RadiusToken = keyof typeof tokens.radius;").ok();
    writeln!(s, "export type ShadowToken = keyof typeof tokens.shadow;").ok();
    writeln!(s, "export type FontFamilyToken = keyof typeof tokens.typography.family;").ok();
    writeln!(s, "export type FontWeightToken = keyof typeof tokens.typography.weight;").ok();
    writeln!(s, "export type TextScaleToken = keyof typeof tokens.typography.scale;").ok();
    writeln!(s, "export type TrackingToken = keyof typeof tokens.typography.tracking;").ok();
    writeln!(s, "export type MotionDurationToken = keyof typeof tokens.motion.duration;").ok();
    writeln!(s, "export type MotionEasingToken = keyof typeof tokens.motion.easing;").ok();
    writeln!(s, "export type BreakpointToken = keyof typeof tokens.breakpoint;").ok();
    writeln!(s, "export type ZToken = keyof typeof tokens.z;").ok();
    s
}

fn emit_color(s: &mut String, color: &ColorToken) {
    let key = quote_key(&color.name);
    let has_dark = color.states.iter().any(|st| st.dark.is_some());
    let single_base = color.states.len() == 1
        && color.states.first().map(|st| st.kind) == Some(ColorStateKind::Base);

    if single_base && !has_dark {
        // Single hex shape.
        let val = &color.states[0].value;
        writeln!(s, "    {}: {},", key, ts_string(val)).ok();
        return;
    }

    if has_dark {
        // Multi-state with dark — each state becomes { light, dark }.
        writeln!(s, "    {}: {{", key).ok();
        for state in &color.states {
            let state_key = state_kind_key(state.kind);
            match &state.dark {
                Some(dark) => writeln!(
                    s,
                    "      {}: {{ light: {}, dark: {} }},",
                    state_key,
                    ts_string(&state.value),
                    ts_string(dark),
                )
                .ok(),
                None => writeln!(s, "      {}: {},", state_key, ts_string(&state.value)).ok(),
            };
        }
        writeln!(s, "    }},").ok();
        return;
    }

    // Multi-state, no dark — flat per-state map.
    writeln!(s, "    {}: {{", key).ok();
    for state in &color.states {
        let state_key = state_kind_key(state.kind);
        writeln!(s, "      {}: {},", state_key, ts_string(&state.value)).ok();
    }
    writeln!(s, "    }},").ok();
}

fn state_kind_key(kind: ColorStateKind) -> &'static str {
    match kind {
        ColorStateKind::Base => "base",
        ColorStateKind::Hover => "hover",
        ColorStateKind::Active => "active",
        ColorStateKind::Foreground => "foreground",
    }
}

/// Quote a key only when it isn't a legal unquoted JS/TS identifier (starts
/// with a digit, contains punctuation, etc.). Authored names like `"2xl"`,
/// `"3xl"`, `"16"` reach us as strings and must stay quoted.
fn quote_key(name: &str) -> String {
    if is_safe_ident(name) {
        name.to_owned()
    } else {
        format!("\"{}\"", escape_string(name))
    }
}

fn is_safe_ident(s: &str) -> bool {
    let mut it = s.chars();
    match it.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }
    it.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn ts_string(value: &str) -> String {
    format!("\"{}\"", escape_string(value))
}

fn escape_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::design::ir::{
        ColorState, ColorStateKind, ColorToken, Design, EasingToken, FamilyToken, Motion,
        ScaleToken, ShadowToken, TextScaleToken, TrackingToken, Typography, WeightToken, ZToken,
    };

    fn minimal_design() -> Design {
        Design {
            name: "tiny".to_owned(),
            extends: None,
            colors: vec![ColorToken {
                name: "success".to_owned(),
                states: vec![ColorState {
                    kind: ColorStateKind::Base,
                    value: "#16a34a".to_owned(),
                    dark: None,
                }],
                span_ref: None,
            }],
            typography: Typography {
                families: vec![FamilyToken {
                    name: "sans".to_owned(),
                    value: "Inter, sans-serif".to_owned(),
                }],
                scale: vec![TextScaleToken {
                    name: "base".to_owned(),
                    size: "1rem".to_owned(),
                    line_height: "1.5rem".to_owned(),
                }],
                weights: vec![WeightToken {
                    name: "regular".to_owned(),
                    value: 400,
                }],
                tracking: vec![],
            },
            spaces: vec![ScaleToken {
                name: "4".to_owned(),
                value: "1rem".to_owned(),
            }],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            span_ref: None,
        }
    }

    #[test]
    fn minimal_fixture_emits_single_color_flat() {
        let out = emit_tokens_ts(&minimal_design());
        assert!(out.contains("success: \"#16a34a\","));
        assert!(out.contains("sans: \"Inter, sans-serif\","));
        // "4" must stay quoted because it starts with a digit.
        assert!(out.contains("\"4\": \"1rem\","));
        assert!(out.contains("export type ColorToken = keyof typeof tokens.color;"));
    }

    #[test]
    fn multi_state_color_emits_nested_object() {
        let mut d = minimal_design();
        d.colors.push(ColorToken {
            name: "primary".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#7c3aed".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Hover,
                    value: "#6d28d9".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Foreground,
                    value: "#ffffff".to_owned(),
                    dark: None,
                },
            ],
            span_ref: None,
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("primary: {"));
        assert!(out.contains("base: \"#7c3aed\","));
        assert!(out.contains("hover: \"#6d28d9\","));
        assert!(out.contains("foreground: \"#ffffff\","));
        // Must NOT have light/dark nesting for this token.
        assert!(!out.contains("light: \"#7c3aed\""));
    }

    #[test]
    fn dark_variant_promotes_states_to_light_dark_objects() {
        let mut d = minimal_design();
        d.colors.push(ColorToken {
            name: "background".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#ffffff".to_owned(),
                    dark: Some("#09090b".to_owned()),
                },
                ColorState {
                    // No dark — should stay as light only (single value) inside the dark-shape.
                    kind: ColorStateKind::Foreground,
                    value: "#09090b".to_owned(),
                    dark: None,
                },
            ],
            span_ref: None,
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("background: {"));
        assert!(out.contains("base: { light: \"#ffffff\", dark: \"#09090b\" },"));
        // The state with no dark stays as a single string in the multi-state-with-dark shape.
        assert!(out.contains("foreground: \"#09090b\","));
    }

    #[test]
    fn empty_groups_do_not_crash() {
        let d = Design {
            name: "empty".to_owned(),
            extends: None,
            colors: vec![],
            typography: Typography::default(),
            spaces: vec![],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            span_ref: None,
        };
        let out = emit_tokens_ts(&d);
        // Should still have the wrapper + all group keys present, just empty bodies.
        assert!(out.contains("color: {"));
        assert!(out.contains("typography: {"));
        assert!(out.contains("space: {"));
        assert!(out.contains("} as const;"));
    }

    #[test]
    fn z_index_emits_as_number_not_string() {
        let mut d = minimal_design();
        d.z_indices.push(ZToken {
            name: "modal".to_owned(),
            value: 1300,
        });
        let out = emit_tokens_ts(&d);
        // Number literal — no quotes.
        assert!(out.contains("modal: 1300,"));
        assert!(!out.contains("\"1300\""));
    }

    #[test]
    fn shadow_string_with_inner_quotes_does_not_escape_badly() {
        let mut d = minimal_design();
        d.shadows.push(ShadowToken {
            name: "sm".to_owned(),
            value: "0 1px 2px 0 rgb(0 0 0 / 0.05)".to_owned(),
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("sm: \"0 1px 2px 0 rgb(0 0 0 / 0.05)\","));
    }

    #[test]
    fn motion_easing_with_cubic_bezier_preserved() {
        let mut d = minimal_design();
        d.motion.easings.push(EasingToken {
            name: "out".to_owned(),
            value: "cubic-bezier(0, 0, 0.2, 1)".to_owned(),
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("out: \"cubic-bezier(0, 0, 0.2, 1)\","));
    }

    #[test]
    fn quoted_scale_name_is_preserved() {
        let mut d = minimal_design();
        d.typography.scale.push(TextScaleToken {
            name: "2xl".to_owned(),
            size: "1.5rem".to_owned(),
            line_height: "2rem".to_owned(),
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("\"2xl\": { size: \"1.5rem\", lineHeight: \"2rem\" },"));
    }

    #[test]
    fn tracking_negative_em_value_preserved_as_string() {
        let mut d = minimal_design();
        d.typography.tracking.push(TrackingToken {
            name: "tight".to_owned(),
            value: "-0.025em".to_owned(),
        });
        let out = emit_tokens_ts(&d);
        assert!(out.contains("tight: \"-0.025em\","));
    }
}

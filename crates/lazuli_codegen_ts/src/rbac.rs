//! RBAC catalog TS emission — `dist/ts-<frontend>/rbac/rbac.gen.ts`.
//!
//! Type-only catalog mirroring the Go output. Closed `Permissions`
//! const object + `Permission` union type + `Roles` const map + a
//! `hasPermission(role, perm)` helper for conditional UI rendering.
//!
//! See `docs/proposals/rbac-catalog-vocab.md` §Codegen-TypeScript.
//!
//! v0.1 ships the full catalog to every frontend (audience-scoping
//! deferred — admin perms reach every bundle). Pilot evidence
//! determines if audience filters are needed before locking the
//! shape in v0.2.

use lazuli_ir::Module;

/// Emit `dist/ts-<frontend>/rbac/rbac.gen.ts` content. Returns `None`
/// when the module declares no `permission` / `role` catalog.
pub fn emit_rbac_ts(module: &Module) -> Option<String> {
    let catalog = module.rbac.as_ref()?;
    if catalog.permissions.is_empty() && catalog.roles.is_empty() {
        return None;
    }

    let mut out = String::new();
    out.push_str("// Code generated by lazuli; DO NOT EDIT.\n");
    out.push_str("// source: rbac catalog (docs/proposals/rbac-catalog-vocab.md)\n");
    out.push('\n');

    // Permissions const map.
    out.push_str("export const Permissions = {\n");
    for perm in &catalog.permissions {
        out.push_str(&format!(
            "  {}: {:?},\n",
            ts_permission_key(&perm.name),
            perm.name
        ));
    }
    out.push_str("} as const;\n\n");

    out.push_str("export type Permission = (typeof Permissions)[keyof typeof Permissions];\n\n");

    // Roles const map (closure baked).
    out.push_str("export const Roles = {\n");
    for role in &catalog.roles {
        out.push_str(&format!("  {}: {{\n", ts_role_key(&role.name)));
        out.push_str(&format!("    name: {:?},\n", role.name));
        out.push_str("    grants: [");
        for (i, perm) in role.closure.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            out.push_str(&format!("{:?}", perm));
        }
        out.push_str("] as const,\n");
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n\n");

    out.push_str("export type RoleName = (typeof Roles)[keyof typeof Roles]['name'];\n\n");

    // hasPermission helper.
    out.push_str("export function hasPermission(role: string, perm: Permission): boolean {\n");
    out.push_str("  for (const key in Roles) {\n");
    out.push_str("    const r = (Roles as Record<string, { name: string; grants: readonly string[] }>)[key];\n");
    out.push_str("    if (r.name === role) {\n");
    out.push_str("      return (r.grants as readonly string[]).includes(perm);\n");
    out.push_str("    }\n");
    out.push_str("  }\n");
    out.push_str("  return false;\n");
    out.push_str("}\n\n");

    out.push_str("export function hasRole(role: string, name: string): boolean {\n");
    out.push_str("  return role === name;\n");
    out.push_str("}\n");

    Some(out)
}

/// `"users:read:own"` -> `UsersReadOwn` for TS const keys.
fn ts_permission_key(name: &str) -> String {
    let mut out = String::new();
    for seg in name.split(':') {
        out.push_str(&pascal_case(seg));
    }
    out
}

/// `"sales_manager"` -> `SalesManager`.
fn ts_role_key(name: &str) -> String {
    pascal_case(name)
}

fn pascal_case(s: &str) -> String {
    let mut out = String::new();
    let mut capitalize_next = true;
    for c in s.chars() {
        if c == '_' || c == '-' {
            capitalize_next = true;
        } else if capitalize_next {
            out.extend(c.to_uppercase());
            capitalize_next = false;
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use lazuli_ir::{Module, PermissionEntry, RbacCatalog, RoleEntry, RoleGrants};

    fn mk_module(catalog: Option<RbacCatalog>) -> Module {
        Module {
            workspace: None,
            contracts: vec![],
            app: None,
            registry: None,
            profiles: vec![],
            design: None,
            rbac: catalog,
            features: vec![],
        }
    }

    #[test]
    fn returns_none_without_catalog() {
        assert!(emit_rbac_ts(&mk_module(None)).is_none());
    }

    #[test]
    fn emits_permissions_roles_and_helper() {
        let m = mk_module(Some(RbacCatalog {
            permissions: vec![PermissionEntry {
                name: "users:read".into(),
                segments: vec!["users".into(), "read".into()],
                span_ref: None,
            }],
            roles: vec![RoleEntry {
                name: "viewer".into(),
                inherits: None,
                grants: RoleGrants::Explicit(vec!["users:read".into()]),
                closure: vec!["users:read".into()],
                span_ref: None,
            }],
        }));
        let out = emit_rbac_ts(&m).expect("emits");
        assert!(out.contains("export const Permissions"));
        assert!(out.contains("UsersRead: \"users:read\""));
        assert!(out.contains("export const Roles"));
        assert!(out.contains("Viewer:"));
        assert!(out.contains("export function hasPermission"));
    }
}

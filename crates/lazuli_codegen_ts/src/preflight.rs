//! Per-feature `preflight.gen.ts` emitter (LAZ-SEMANTIC-AUTO-VALIDATE
//! Wave 2). Walks every command on a feature, gathers fields whose
//! type carries a `@semantic.X` plugin scalar with a non-empty
//! `ts_validator`, and emits one `registerPreflight(...)` call per
//! eligible command. Apps import this file once at startup; the
//! lazuli runtime's preflight registry then short-circuits invalid
//! input before the network round-trip.
//!
//! Output: `dist/<target>/<feature>/<feature>.preflight.gen.ts`. The
//! generator returns `None` when the feature has zero eligible
//! commands so the file is never written.

use lazuli_ir::{BuiltinType, Command, CommandInput, Feature, Module, TypeRef};
use std::collections::{BTreeMap, BTreeSet};

#[derive(Debug, Clone)]
struct PreflightSlot {
    json_field: String,
    optional: bool,
    /// Imported alias.fn (e.g. `scalarsBr.validateCPF`).
    call: String,
    error_code: String,
    message_key: String,
}

#[derive(Debug, Clone)]
struct PreflightCommand {
    qualified_name: String,
    slots: Vec<PreflightSlot>,
}

/// Per-package import bucket — `import { fn, fn2 } from "pkg"`.
type ImportBuckets = BTreeMap<String, BTreeSet<String>>;

/// Top-level `dist/<target>/preflight.gen.ts` — side-effect-imports
/// every per-feature `preflight.gen.ts` so apps can `import
/// "@app/sdk/preflight.gen"` once at startup and pick up every
/// registration without going through each feature's barrel.
pub fn emit_preflight_index_ts(module: &Module) -> Option<String> {
    let mut features: Vec<&str> = module
        .features
        .iter()
        .filter(|f| feature_has_eligible_command(f))
        .map(|f| f.name.as_str())
        .collect();
    if features.is_empty() {
        return None;
    }
    features.sort();
    let mut s = String::new();
    s.push_str("// Code generated by lazuli; DO NOT EDIT.\n");
    s.push_str("// LAZ-SEMANTIC-AUTO-VALIDATE — side-effect import of every\n");
    s.push_str("// per-feature preflight.gen.ts. Apps import this file once\n");
    s.push_str("// at startup; the preflight registry is populated immediately.\n");
    for f in &features {
        s.push_str(&format!("import \"./{f}/{f}.preflight.gen.js\";\n"));
    }
    Some(s)
}

/// Public predicate used by main.rs to decide whether to wire the
/// barrel side-effect import. Kept in sync with `emit_preflight_ts`'s
/// eligibility check.
pub fn feature_has_eligible_command(feature: &Feature) -> bool {
    feature
        .commands
        .iter()
        .any(|c| has_eligible_slot(c))
}

fn has_eligible_slot(command: &Command) -> bool {
    let CommandInput::Typed(slots) = &command.input else {
        return false;
    };
    slots.iter().any(|slot| {
        if slot.validate_skip {
            return false;
        }
        let TypeRef::Builtin(BuiltinType::SemanticPluginType {
            ts_package,
            ts_validator,
            ..
        }) = &slot.type_ref
        else {
            return false;
        };
        !ts_validator.is_empty() && !ts_package.is_empty()
    })
}

pub fn emit_preflight_ts(feature: &Feature) -> Option<String> {
    let mut imports: ImportBuckets = BTreeMap::new();
    let mut commands = Vec::new();
    for command in &feature.commands {
        let Some(pc) = preflight_for_command(feature, command, &mut imports) else {
            continue;
        };
        commands.push(pc);
    }
    if commands.is_empty() {
        return None;
    }

    let mut s = String::new();
    s.push_str("// Code generated by lazuli; DO NOT EDIT.\n");
    s.push_str("// LAZ-SEMANTIC-AUTO-VALIDATE — preflight registrations\n");
    s.push_str("// for commands with at least one @semantic.X field whose\n");
    s.push_str("// plugin declares a TS validator.\n");
    s.push_str("import { registerPreflight, type PreflightResult } from \"@lazuli/runtime/react\";\n");
    for (pkg, fns) in &imports {
        let names: Vec<String> = fns.iter().cloned().collect();
        s.push_str(&format!(
            "import {{ {} }} from \"{}\";\n",
            names.join(", "),
            pkg
        ));
    }
    s.push('\n');
    for pc in &commands {
        emit_one(&mut s, &pc);
        s.push('\n');
    }
    Some(s)
}

fn emit_one(s: &mut String, pc: &PreflightCommand) {
    s.push_str(&format!(
        "registerPreflight({:?}, (raw): PreflightResult => {{\n",
        pc.qualified_name
    ));
    s.push_str("  const input = raw as Record<string, unknown>;\n");
    s.push_str("  const fields: Record<string, string> = {};\n");
    let any_keys = pc.slots.iter().any(|sl| !sl.message_key.is_empty());
    if any_keys {
        s.push_str("  const keys: Record<string, string> = {};\n");
    }
    for sl in &pc.slots {
        // Drop guards for empty / null / undefined inputs.
        s.push_str(&format!(
            "  {{\n    const v = input[{:?}];\n",
            sl.json_field
        ));
        if sl.optional {
            s.push_str("    if (typeof v === \"string\" && v !== \"\") {\n");
        } else {
            s.push_str("    if (typeof v === \"string\" && v !== \"\") {\n");
        }
        s.push_str(&format!("      const err = {}(v);\n", sl.call));
        s.push_str("      if (err) {\n");
        s.push_str(&format!(
            "        fields[{:?}] = {:?};\n",
            sl.json_field, sl.error_code
        ));
        if !sl.message_key.is_empty() {
            s.push_str(&format!(
                "        keys[{:?}] = {:?};\n",
                sl.json_field, sl.message_key
            ));
        }
        s.push_str("      }\n");
        s.push_str("    }\n");
        s.push_str("  }\n");
    }
    s.push_str("  if (Object.keys(fields).length === 0) return { ok: true };\n");
    if any_keys {
        s.push_str("  return { ok: false, fields, fieldMessageKeys: keys };\n");
    } else {
        s.push_str("  return { ok: false, fields };\n");
    }
    s.push_str("});\n");
}

fn preflight_for_command(
    feature: &Feature,
    command: &Command,
    imports: &mut ImportBuckets,
) -> Option<PreflightCommand> {
    let slots = match &command.input {
        CommandInput::Typed(slots) => slots,
        _ => return None,
    };
    let mut out = Vec::new();
    for slot in slots {
        if slot.validate_skip {
            continue;
        }
        let TypeRef::Builtin(BuiltinType::SemanticPluginType {
            ts_package,
            ts_validator,
            error_code,
            message_key,
            ..
        }) = &slot.type_ref
        else {
            continue;
        };
        if ts_validator.is_empty() || ts_package.is_empty() {
            continue;
        }
        let alias = ts_validator.clone();
        imports
            .entry(ts_package.clone())
            .or_default()
            .insert(alias.clone());
        out.push(PreflightSlot {
            json_field: slot.name.clone(),
            optional: !slot.required,
            call: alias,
            error_code: error_code.clone(),
            message_key: message_key.clone(),
        });
    }
    if out.is_empty() {
        return None;
    }
    Some(PreflightCommand {
        qualified_name: format!("{}.{}", feature.name, command.name),
        slots: out,
    })
}

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use lazuli_ir::{
    AppManifest, AppRoute, Experience, Feature, Module, Platform, PlatformSurface, Resource,
    SurfaceTarget, View, ViewGuard,
};

const FIXTURE_ROLES: [&str; 3] = ["host", "traveler", "operator"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlaywrightFixtureConfig {
    pub helpers: Option<PlaywrightFixtureHelperImports>,
}

impl PlaywrightFixtureConfig {
    pub fn without_helpers() -> Self {
        Self { helpers: None }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlaywrightFixtureHelperImports {
    pub api_import: String,
    pub session_import: String,
    pub lifecycle_import: Option<String>,
    pub lifecycle_seeders: Vec<LifecycleSeeder>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LifecycleSeeder {
    pub role: String,
    pub function_name: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct LifecycleSpec {
    states: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct PolicyAtom {
    namespace: String,
    name: String,
}

pub fn emit_playwright_fixtures(
    module: &Module,
    routes: &[AppRoute],
    surfaces: &[PlatformSurface],
    experiences: &[Experience],
    config: &PlaywrightFixtureConfig,
) -> String {
    let lifecycles = lifecycle_specs_by_role(module);
    let routes_by_role = routes_by_role(module, routes, surfaces, experiences);

    let mut s = String::new();
    s.push_str("// Code generated by lazuli; DO NOT EDIT.\n");
    s.push_str("import type { APIRequestContext, Page } from '@playwright/test';\n");
    if let Some(helpers) = &config.helpers {
        writeln!(
            s,
            "import {{ registerWithRole }} from '{}';",
            escape_ts_single_quoted(&helpers.api_import)
        )
        .ok();
        writeln!(
            s,
            "import type {{ Role }} from '{}';",
            escape_ts_single_quoted(&helpers.api_import)
        )
        .ok();
        writeln!(
            s,
            "import {{ signInAs }} from '{}';",
            escape_ts_single_quoted(&helpers.session_import)
        )
        .ok();
        if let Some(lifecycle_import) = &helpers.lifecycle_import {
            let imports: Vec<&str> = helpers
                .lifecycle_seeders
                .iter()
                .map(|seeder| seeder.function_name.as_str())
                .collect::<BTreeSet<_>>()
                .into_iter()
                .collect();
            if !imports.is_empty() {
                writeln!(
                    s,
                    "import {{ {} }} from '{}';",
                    imports.join(", "),
                    escape_ts_single_quoted(lifecycle_import)
                )
                .ok();
            }
        }
    }
    s.push('\n');

    for role in FIXTURE_ROLES {
        let type_name = lifecycle_type_name(role);
        let states = lifecycles
            .get(role)
            .map(|spec| spec.states.as_slice())
            .unwrap_or(&[]);
        write_lifecycle_type(&mut s, &type_name, states);
    }

    s.push('\n');
    if config.helpers.is_some() {
        s.push_str("export type FixtureRole = Extract<Role, 'host' | 'traveler' | 'operator'>;\n");
        s.push_str("export type FixtureActor = Awaited<ReturnType<typeof registerWithRole>>;\n");
    } else {
        s.push_str("export type FixtureRole = 'host' | 'traveler' | 'operator';\n");
        s.push_str("export interface FixtureActor {\n");
        s.push_str(
            "  user: { id: number; email: string; role: FixtureRole | null; orgId: number };\n",
        );
        s.push_str("  password: string;\n");
        s.push_str("  token: string;\n");
        s.push_str("}\n");
    }
    s.push_str("type PageWithRequest = Page & { request: APIRequestContext };\n\n");

    s.push_str("type LifecycleStateByRole = {\n");
    for role in FIXTURE_ROLES {
        writeln!(s, "  {}: {};", role, lifecycle_type_name(role)).ok();
    }
    s.push_str("};\n\n");

    s.push_str("export type FixtureOptions<R extends FixtureRole = FixtureRole> = {\n");
    s.push_str("  lifecycle?: LifecycleStateByRole[R];\n");
    s.push_str("  request?: APIRequestContext;\n");
    s.push_str("  slug?: string;\n");
    s.push_str("  goto?: string;\n");
    s.push_str("};\n\n");

    for role in FIXTURE_ROLES {
        writeln!(
            s,
            "export async function as{}(page: Page, opts: FixtureOptions<'{}'> = {{}}): Promise<FixtureActor> {{",
            pascal_case(role),
            role
        )
        .ok();
        writeln!(s, "  return signInWithRole(page, '{}', opts);", role).ok();
        s.push_str("}\n\n");
    }

    s.push_str("export async function atLifecycle<R extends FixtureRole>(\n");
    s.push_str("  page: Page,\n");
    s.push_str("  role: R,\n");
    s.push_str("  lifecycleState: LifecycleStateByRole[R],\n");
    s.push_str("): Promise<FixtureActor> {\n");
    s.push_str("  return signInWithRole(page, role, { lifecycle: lifecycleState });\n");
    s.push_str("}\n\n");

    write_routes_by_role(&mut s, &routes_by_role);

    if config.helpers.is_some() {
        s.push_str("function requestForPage(page: Page, opts?: { request?: APIRequestContext }): APIRequestContext {\n");
        s.push_str("  return opts?.request ?? (page as PageWithRequest).request;\n");
        s.push_str("}\n\n");
        s.push_str("async function signInWithRole<R extends FixtureRole>(\n");
        s.push_str("  page: Page,\n");
        s.push_str("  role: R,\n");
        s.push_str("  opts: FixtureOptions<R>,\n");
        s.push_str("): Promise<FixtureActor> {\n");
        s.push_str("  const request = requestForPage(page, opts);\n");
        s.push_str("  const actor = await registerWithRole(request, role, opts.slug ? { slug: opts.slug } : undefined);\n");
        s.push_str("  if (opts.lifecycle !== undefined) {\n");
        s.push_str("    await seedLifecycle(request, actor, role, opts.lifecycle);\n");
        s.push_str("  }\n");
        s.push_str("  await signInAs(page, actor.token);\n");
        s.push_str("  if (opts.goto) await page.goto(opts.goto);\n");
        s.push_str("  return actor;\n");
        s.push_str("}\n\n");
    } else {
        s.push_str("async function signInWithRole<R extends FixtureRole>(\n");
        s.push_str("  page: Page,\n");
        s.push_str("  role: R,\n");
        s.push_str("  opts: FixtureOptions<R>,\n");
        s.push_str("): Promise<FixtureActor> {\n");
        s.push_str("  void page;\n");
        s.push_str("  void role;\n");
        s.push_str("  void opts;\n");
        s.push_str("  throw new Error('TODO(lazuli): import app-owned e2e helpers for registerWithRole/signInAs before using generated Playwright fixtures.');\n");
        s.push_str("}\n\n");
    }

    write_seed_lifecycle(&mut s, config.helpers.as_ref());
    s
}

fn write_lifecycle_type(s: &mut String, type_name: &str, states: &[String]) {
    if states.is_empty() {
        writeln!(s, "export type {} = never;", type_name).ok();
        return;
    }
    writeln!(s, "export type {} =", type_name).ok();
    for (index, state) in states.iter().enumerate() {
        let suffix = if index + 1 == states.len() { ";" } else { "" };
        writeln!(s, "  | '{}'{suffix}", escape_ts_single_quoted(state)).ok();
    }
}

fn write_routes_by_role(s: &mut String, routes: &BTreeMap<String, BTreeSet<String>>) {
    s.push_str("const routesByRole = {\n");
    for role in FIXTURE_ROLES {
        s.push_str("  ");
        s.push_str(role);
        s.push_str(": [");
        let paths = routes.get(role);
        if let Some(paths) = paths {
            if !paths.is_empty() {
                s.push('\n');
                for path in paths {
                    writeln!(s, "    '{}',", escape_ts_single_quoted(path)).ok();
                }
                s.push_str("  ");
            }
        }
        s.push_str("],\n");
    }
    s.push_str("} as const satisfies Record<FixtureRole, readonly string[]>;\n\n");
    s.push_str("export function routesForRole(role: FixtureRole): string[] {\n");
    s.push_str("  return [...routesByRole[role]];\n");
    s.push_str("}\n\n");
}

fn write_seed_lifecycle(s: &mut String, helpers: Option<&PlaywrightFixtureHelperImports>) {
    let seeder_by_role: BTreeMap<&str, &str> = helpers
        .into_iter()
        .flat_map(|helpers| helpers.lifecycle_seeders.iter())
        .map(|seeder| (seeder.role.as_str(), seeder.function_name.as_str()))
        .collect();

    s.push_str("async function seedLifecycle<R extends FixtureRole>(\n");
    s.push_str("  request: APIRequestContext,\n");
    s.push_str("  actor: FixtureActor,\n");
    s.push_str("  role: R,\n");
    s.push_str("  lifecycle: LifecycleStateByRole[R],\n");
    s.push_str("): Promise<void> {\n");
    s.push_str("  switch (role) {\n");
    for role in FIXTURE_ROLES {
        writeln!(s, "    case '{}':", role).ok();
        if let Some(function_name) = seeder_by_role.get(role) {
            writeln!(
                s,
                "      await {}(request, actor.user.id, actor.user.orgId, lifecycle as {});",
                function_name,
                lifecycle_type_name(role)
            )
            .ok();
            s.push_str("      return;\n");
        } else {
            writeln!(
                s,
                "      throw new Error('TODO(lazuli): add an app-owned lifecycle seeding helper for role `{}`.');",
                role
            )
            .ok();
        }
    }
    s.push_str("    default:\n");
    s.push_str("      throw new Error(`Unsupported fixture role: ${String(role)}`);\n");
    s.push_str("  }\n");
    s.push_str("}\n");
}

fn lifecycle_specs_by_role(module: &Module) -> BTreeMap<String, LifecycleSpec> {
    let mut out = BTreeMap::new();
    for role in FIXTURE_ROLES {
        if let Some((_, resource)) = module
            .features
            .iter()
            .find_map(|feature| lifecycle_resource_for_role(feature, role).map(|r| (feature, r)))
        {
            if let Some(lifecycle) = resource.lifecycle.as_ref() {
                out.insert(
                    role.to_owned(),
                    LifecycleSpec {
                        states: lifecycle
                            .states
                            .iter()
                            .map(|state| state.name.clone())
                            .collect(),
                    },
                );
            }
        }
    }
    out
}

fn lifecycle_resource_for_role<'a>(feature: &'a Feature, role: &str) -> Option<&'a Resource> {
    feature
        .resources
        .iter()
        .find(|resource| resource.lifecycle.is_some() && canonical(&resource.name) == role)
        .or_else(|| {
            if feature.name == role {
                feature
                    .resources
                    .iter()
                    .find(|resource| resource.lifecycle.is_some())
            } else {
                None
            }
        })
}

fn routes_by_role(
    module: &Module,
    routes: &[AppRoute],
    surfaces: &[PlatformSurface],
    experiences: &[Experience],
) -> BTreeMap<String, BTreeSet<String>> {
    let mut out: BTreeMap<String, BTreeSet<String>> = FIXTURE_ROLES
        .into_iter()
        .map(|role| (role.to_owned(), BTreeSet::new()))
        .collect();
    let policy_lookup = build_policy_lookup(&module.features);
    for route in routes {
        let Some(path) = route.path.as_ref() else {
            continue;
        };
        let roles = roles_for_route(
            route,
            module.app.as_ref(),
            surfaces,
            experiences,
            &policy_lookup,
        );
        for role in roles {
            if let Some(paths) = out.get_mut(role.as_str()) {
                paths.insert(path.clone());
            }
        }
    }

    for feature in &module.features {
        for surface in &feature.surfaces {
            if surface.target != SurfaceTarget::Web {
                continue;
            }
            for audience in &surface.audiences {
                let mut roles = roles_from_atoms(audience.requires.iter().map(|atom| PolicyAtom {
                    namespace: atom.namespace.clone(),
                    name: atom.name.clone(),
                }));
                if FIXTURE_ROLES.contains(&audience.name.as_str()) {
                    roles.insert(audience.name.clone());
                }
                for view in &audience.views {
                    if let Some(path) = view_route(view) {
                        for role in &roles {
                            if let Some(paths) = out.get_mut(role.as_str()) {
                                paths.insert(path.to_owned());
                            }
                        }
                    }
                }
            }
        }
    }

    out
}

fn roles_for_route(
    route: &AppRoute,
    app: Option<&AppManifest>,
    surfaces: &[PlatformSurface],
    experiences: &[Experience],
    policy_lookup: &BTreeMap<(String, String), Vec<PolicyAtom>>,
) -> BTreeSet<String> {
    let default_feature = route_target_feature(route.to.as_deref())
        .or_else(|| route.surface.as_deref().and_then(surface_feature))
        .unwrap_or_else(|| route_feature_from_name(&route.name));
    let view_name =
        route_target_view_name(route.to.as_deref()).unwrap_or_else(|| route.name.clone());
    let route_audience = route.audience.as_deref();
    let (view_guard, audience_guard) = surface_guards(
        route,
        &default_feature,
        &view_name,
        route_audience,
        surfaces,
    );
    let experience_guard = experiences
        .iter()
        .find(|experience| experience.name == default_feature)
        .and_then(|experience| experience.views.iter().find(|view| view.name == view_name))
        .and_then(|view| view.guard.as_ref());

    let guard_chain = [
        route.guard.as_ref(),
        view_guard,
        experience_guard,
        audience_guard,
    ];
    if let Some(policy_texts) = guard_chain
        .iter()
        .find_map(|guard| guard.map(|guard| guard.policy.as_slice()))
    {
        return roles_from_policy_refs(
            policy_texts.iter().map(String::as_str),
            policy_lookup,
            &default_feature,
        );
    }

    if let Some(default_policy) = app
        .and_then(|app| app.route_guard.as_ref())
        .and_then(|defaults| defaults.default_policy.as_deref())
    {
        let roles = roles_from_policy_refs(
            std::iter::once(default_policy),
            policy_lookup,
            &default_feature,
        );
        if !roles.is_empty() {
            return roles;
        }
    }

    route_audience
        .filter(|audience| FIXTURE_ROLES.contains(audience))
        .map(|audience| BTreeSet::from([audience.to_owned()]))
        .unwrap_or_default()
}

fn surface_guards<'a>(
    route: &AppRoute,
    default_feature: &str,
    view_name: &str,
    route_audience: Option<&str>,
    surfaces: &'a [PlatformSurface],
) -> (Option<&'a ViewGuard>, Option<&'a ViewGuard>) {
    let surface = surfaces
        .iter()
        .filter(|surface| surface.platform == Platform::Web)
        .find(|surface| {
            let surface_name = route.surface.as_deref();
            if let Some(surface_name) = surface_name {
                let mut parts = surface_name.split_whitespace();
                if parts.next() != Some(surface.experience.as_str()) {
                    return false;
                }
            }
            surface.experience == default_feature
                || surface.uses_experience.as_deref() == Some(default_feature)
        });
    let audience = surface.and_then(|surface| {
        route_audience
            .and_then(|name| {
                surface
                    .audiences
                    .iter()
                    .find(|audience| audience.name == name)
            })
            .or_else(|| {
                if route_audience.is_none() {
                    surface.audiences.first()
                } else {
                    None
                }
            })
    });
    let view_guard = audience
        .and_then(|audience| audience.views.iter().find(|view| view.name == view_name))
        .and_then(|view| view.guard.as_ref());
    let audience_guard = audience.and_then(|audience| audience.guard.as_ref());
    (view_guard, audience_guard)
}

fn roles_from_policy_refs<'a>(
    policies: impl Iterator<Item = &'a str>,
    policy_lookup: &BTreeMap<(String, String), Vec<PolicyAtom>>,
    default_feature: &str,
) -> BTreeSet<String> {
    let atoms =
        policies.flat_map(|policy| resolve_policy_atoms(policy, policy_lookup, default_feature));
    roles_from_atoms(atoms)
}

fn roles_from_atoms(atoms: impl Iterator<Item = PolicyAtom>) -> BTreeSet<String> {
    atoms
        .filter(|atom| atom.namespace == "role")
        .filter(|atom| FIXTURE_ROLES.contains(&atom.name.as_str()))
        .map(|atom| atom.name)
        .collect()
}

fn build_policy_lookup(features: &[Feature]) -> BTreeMap<(String, String), Vec<PolicyAtom>> {
    let mut out = BTreeMap::new();
    for feature in features {
        for category in &feature.policies.categories {
            let atoms = category
                .atoms
                .iter()
                .filter_map(|atom| parse_policy_atom(atom))
                .collect();
            out.insert((feature.name.clone(), category.name.clone()), atoms);
        }
    }
    out
}

fn resolve_policy_atoms(
    policy: &str,
    policy_lookup: &BTreeMap<(String, String), Vec<PolicyAtom>>,
    default_feature: &str,
) -> Vec<PolicyAtom> {
    if let Some(atom) = parse_policy_atom(policy) {
        return vec![atom];
    }
    if let Some(role) = policy.strip_prefix("@policy.role.") {
        if FIXTURE_ROLES.contains(&role) {
            return vec![PolicyAtom {
                namespace: "role".to_owned(),
                name: role.to_owned(),
            }];
        }
    }
    let Some((feature, category)) = parse_policy_ref(policy, default_feature) else {
        return Vec::new();
    };
    policy_lookup
        .get(&(feature, category))
        .cloned()
        .unwrap_or_default()
}

fn parse_policy_ref(policy: &str, default_feature: &str) -> Option<(String, String)> {
    let tail = policy.strip_prefix("@policy.")?;
    let mut parts = tail.split('.');
    let first = parts.next()?.trim();
    let second = parts.next();
    if let Some(second) = second {
        let rest = std::iter::once(second)
            .chain(parts)
            .collect::<Vec<_>>()
            .join(".");
        Some((first.to_owned(), rest))
    } else {
        Some((default_feature.to_owned(), first.to_owned()))
    }
}

fn parse_policy_atom(value: &str) -> Option<PolicyAtom> {
    let raw = value.trim().trim_start_matches('@');
    let (namespace, name) = raw.split_once('.')?;
    if namespace.is_empty() || name.is_empty() || namespace == "policy" {
        return None;
    }
    Some(PolicyAtom {
        namespace: namespace.to_owned(),
        name: name.to_owned(),
    })
}

fn route_target_feature(value: Option<&str>) -> Option<String> {
    value?
        .split_once(".view.")
        .map(|(feature, _)| feature.to_owned())
}

fn route_target_view_name(value: Option<&str>) -> Option<String> {
    let (_, tail) = value?.split_once(".view.")?;
    let name = tail.split('(').next().unwrap_or(tail).trim();
    if name.is_empty() {
        None
    } else {
        Some(name.to_owned())
    }
}

fn surface_feature(value: &str) -> Option<String> {
    value.split_whitespace().next().map(str::to_owned)
}

fn route_feature_from_name(value: &str) -> String {
    value.split('_').next().unwrap_or("app").to_owned()
}

fn view_route(view: &View) -> Option<&str> {
    match view {
        View::List(view) => view.route.as_deref(),
        View::Detail(view) => view.route.as_deref(),
        View::Create(view) => view.route.as_deref(),
    }
}

fn lifecycle_type_name(role: &str) -> String {
    format!("{}LifecycleState", pascal_case(role))
}

fn canonical(value: &str) -> String {
    value
        .chars()
        .flat_map(|ch| ch.to_lowercase())
        .map(|ch| match ch {
            '-' => '_',
            other => other,
        })
        .collect()
}

fn pascal_case(value: &str) -> String {
    let mut out = String::new();
    for word in value.split(|ch: char| ch == '_' || ch == '-' || ch == ' ') {
        if word.is_empty() {
            continue;
        }
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(&chars.as_str().to_ascii_lowercase());
        }
    }
    out
}

fn escape_ts_single_quoted(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(ch),
        }
    }
    out
}

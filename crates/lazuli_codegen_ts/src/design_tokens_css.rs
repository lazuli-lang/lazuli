//! `tokens.css` emitter — CSS custom properties on `:root` plus a
//! `[data-theme="dark"]` block carrying the per-color `dark` overrides.
//! See `docs/proposals/design-tokens.md` §4.3.
//!
//! Variable naming (§4.3 trailing line of the proposal):
//!   - `--<group>-<name>` for flat tokens, e.g. `--color-success`, `--space-4`.
//!   - `--<group>-<name>-<state>` for color sub-states, e.g.
//!     `--color-primary-base`, `--color-primary-hover`.
//!   - `--text-<size>` paired with `--text-<size>--line-height` for typography
//!     scale (the double-dash on `--line-height` is intentional; mirrors the
//!     Tailwind v4 paired-variable convention quoted in the proposal).
//!
//! Names are emitted kebab-case via `kebab(name)`; the IR already enforces
//! lowercase identifiers (per `docs/grammar.lzi.md`), so the conversion is
//! mostly underscores → hyphens.

use std::fmt::Write;

use super::ir::{ColorStateKind, ColorToken, Design};

/// Emit `dist/ts-web/design/tokens.css` for the given `Design`.
pub fn emit_tokens_css(design: &Design) -> String {
    let mut s = String::new();
    writeln!(s, "/* Code generated by lazuli; DO NOT EDIT. */").ok();
    writeln!(s, "/* Source: design.lzi (design `{}`) */", design.name).ok();
    writeln!(s, ":root {{").ok();

    // Colors
    if !design.colors.is_empty() {
        for color in &design.colors {
            emit_color_light(&mut s, color);
        }
    }

    // Typography
    if !design.typography.families.is_empty() {
        writeln!(s).ok();
        for fam in &design.typography.families {
            writeln!(
                s,
                "  --font-{}: {};",
                kebab(&fam.name),
                fam.value
            )
            .ok();
        }
    }

    if !design.typography.scale.is_empty() {
        writeln!(s).ok();
        for entry in &design.typography.scale {
            let n = kebab(&entry.name);
            writeln!(s, "  --text-{}: {};", n, entry.size).ok();
            writeln!(s, "  --text-{}--line-height: {};", n, entry.line_height).ok();
        }
    }

    if !design.typography.weights.is_empty() {
        writeln!(s).ok();
        for w in &design.typography.weights {
            writeln!(s, "  --font-weight-{}: {};", kebab(&w.name), w.value).ok();
        }
    }

    if !design.typography.tracking.is_empty() {
        writeln!(s).ok();
        for t in &design.typography.tracking {
            writeln!(s, "  --tracking-{}: {};", kebab(&t.name), t.value).ok();
        }
    }

    // Space
    if !design.spaces.is_empty() {
        writeln!(s).ok();
        for tok in &design.spaces {
            writeln!(s, "  --space-{}: {};", kebab(&tok.name), tok.value).ok();
        }
    }

    // Radius
    if !design.radii.is_empty() {
        writeln!(s).ok();
        for tok in &design.radii {
            writeln!(s, "  --radius-{}: {};", kebab(&tok.name), tok.value).ok();
        }
    }

    // Shadow
    if !design.shadows.is_empty() {
        writeln!(s).ok();
        for tok in &design.shadows {
            writeln!(s, "  --shadow-{}: {};", kebab(&tok.name), tok.value).ok();
        }
    }

    // Motion
    if !design.motion.durations.is_empty() {
        writeln!(s).ok();
        for d in &design.motion.durations {
            writeln!(s, "  --duration-{}: {};", kebab(&d.name), d.value).ok();
        }
    }
    if !design.motion.easings.is_empty() {
        writeln!(s).ok();
        for e in &design.motion.easings {
            writeln!(s, "  --easing-{}: {};", kebab(&e.name), e.value).ok();
        }
    }

    // Breakpoint
    if !design.breakpoints.is_empty() {
        writeln!(s).ok();
        for tok in &design.breakpoints {
            writeln!(s, "  --breakpoint-{}: {};", kebab(&tok.name), tok.value).ok();
        }
    }

    // Z
    if !design.z_indices.is_empty() {
        writeln!(s).ok();
        for tok in &design.z_indices {
            writeln!(s, "  --z-{}: {};", kebab(&tok.name), tok.value).ok();
        }
    }

    writeln!(s, "}}").ok();

    // Dark override block — only emit if at least one color state has a dark
    // value.
    let has_dark = design
        .colors
        .iter()
        .flat_map(|c| &c.states)
        .any(|st| st.dark.is_some());
    if has_dark {
        writeln!(s).ok();
        writeln!(s, "[data-theme=\"dark\"] {{").ok();
        for color in &design.colors {
            emit_color_dark(&mut s, color);
        }
        writeln!(s, "}}").ok();
    }

    s
}

fn emit_color_light(s: &mut String, color: &ColorToken) {
    let group = kebab(&color.name);
    let single_base = color.states.len() == 1
        && color.states.first().map(|st| st.kind) == Some(ColorStateKind::Base);

    if single_base {
        let v = &color.states[0].value;
        writeln!(s, "  --color-{}: {};", group, v).ok();
    } else {
        for state in &color.states {
            let suffix = state_kind_suffix(state.kind);
            writeln!(s, "  --color-{}-{}: {};", group, suffix, state.value).ok();
        }
    }
}

fn emit_color_dark(s: &mut String, color: &ColorToken) {
    let group = kebab(&color.name);
    let single_base = color.states.len() == 1
        && color.states.first().map(|st| st.kind) == Some(ColorStateKind::Base);
    for state in &color.states {
        if let Some(dark) = &state.dark {
            if single_base {
                writeln!(s, "  --color-{}: {};", group, dark).ok();
            } else {
                let suffix = state_kind_suffix(state.kind);
                writeln!(s, "  --color-{}-{}: {};", group, suffix, dark).ok();
            }
        }
    }
}

fn state_kind_suffix(kind: ColorStateKind) -> &'static str {
    match kind {
        ColorStateKind::Base => "base",
        ColorStateKind::Hover => "hover",
        ColorStateKind::Active => "active",
        ColorStateKind::Foreground => "foreground",
    }
}

/// Convert `snake_or words` → `snake-or-words`. Author IDs are already
/// lowercase (grammar requires `IDENT_LOWER`), but tokens with quoted names
/// like `"2xl"` carry through unchanged (no underscores to swap).
fn kebab(s: &str) -> String {
    s.chars()
        .map(|c| if c == '_' || c == ' ' { '-' } else { c })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::design::ir::{
        ColorState, ColorStateKind, ColorToken, Design, EasingToken, FamilyToken, Motion,
        ScaleToken, TextScaleToken, TrackingToken, Typography, WeightToken, ZToken,
    };

    fn minimal() -> Design {
        Design {
            name: "tiny".to_owned(),
            extends: None,
            colors: vec![ColorToken {
                name: "success".to_owned(),
                states: vec![ColorState {
                    kind: ColorStateKind::Base,
                    value: "#16a34a".to_owned(),
                    dark: None,
                }],
                span_ref: None,
            }],
            typography: Typography {
                families: vec![FamilyToken {
                    name: "sans".to_owned(),
                    value: "Inter, system-ui, sans-serif".to_owned(),
                }],
                scale: vec![TextScaleToken {
                    name: "base".to_owned(),
                    size: "1rem".to_owned(),
                    line_height: "1.5rem".to_owned(),
                }],
                weights: vec![],
                tracking: vec![],
            },
            spaces: vec![ScaleToken {
                name: "4".to_owned(),
                value: "1rem".to_owned(),
            }],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            span_ref: None,
        }
    }

    #[test]
    fn minimal_emits_root_block_and_single_color() {
        let out = emit_tokens_css(&minimal());
        assert!(out.starts_with("/* Code generated by lazuli; DO NOT EDIT. */"));
        assert!(out.contains(":root {"));
        assert!(out.contains("  --color-success: #16a34a;"));
        assert!(out.contains("  --font-sans: Inter, system-ui, sans-serif;"));
        assert!(out.contains("  --text-base: 1rem;"));
        assert!(out.contains("  --text-base--line-height: 1.5rem;"));
        assert!(out.contains("  --space-4: 1rem;"));
        // No dark block when no dark variants.
        assert!(!out.contains("[data-theme=\"dark\"]"));
    }

    #[test]
    fn multi_state_color_emits_suffixed_vars() {
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "primary".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#7c3aed".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Hover,
                    value: "#6d28d9".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Foreground,
                    value: "#ffffff".to_owned(),
                    dark: None,
                },
            ],
            span_ref: None,
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --color-primary-base: #7c3aed;"));
        assert!(out.contains("  --color-primary-hover: #6d28d9;"));
        assert!(out.contains("  --color-primary-foreground: #ffffff;"));
    }

    #[test]
    fn dark_variants_emit_data_theme_dark_block() {
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "background".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#ffffff".to_owned(),
                    dark: Some("#09090b".to_owned()),
                },
                ColorState {
                    kind: ColorStateKind::Foreground,
                    value: "#71717a".to_owned(),
                    dark: Some("#a1a1aa".to_owned()),
                },
            ],
            span_ref: None,
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("[data-theme=\"dark\"] {"));
        assert!(out.contains("  --color-background-base: #09090b;"));
        assert!(out.contains("  --color-background-foreground: #a1a1aa;"));
        // Light values still in :root.
        assert!(out.contains("  --color-background-base: #ffffff;"));
    }

    #[test]
    fn empty_design_emits_only_empty_root() {
        let d = Design {
            name: "void".to_owned(),
            extends: None,
            colors: vec![],
            typography: Typography::default(),
            spaces: vec![],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            span_ref: None,
        };
        let out = emit_tokens_css(&d);
        assert!(out.contains(":root {"));
        assert!(out.contains("}"));
        assert!(!out.contains("[data-theme"));
    }

    #[test]
    fn empty_easings_does_not_break() {
        let mut d = minimal();
        d.motion.durations.push(ScaleToken {
            name: "fast".to_owned(),
            value: "150ms".to_owned(),
        });
        // motion.easings stays empty
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --duration-fast: 150ms;"));
        assert!(!out.contains("--easing-"));
    }

    #[test]
    fn single_flat_color_with_dark_emits_data_theme_block() {
        // Single Base state with a dark value should still emit dark override
        // — without a state suffix because the light line was also bare.
        let d = Design {
            name: "x".to_owned(),
            extends: None,
            colors: vec![ColorToken {
                name: "card".to_owned(),
                states: vec![ColorState {
                    kind: ColorStateKind::Base,
                    value: "#ffffff".to_owned(),
                    dark: Some("#0c0c0e".to_owned()),
                }],
                span_ref: None,
            }],
            typography: Typography::default(),
            spaces: vec![],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            span_ref: None,
        };
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --color-card: #ffffff;"));
        assert!(out.contains("[data-theme=\"dark\"] {"));
        assert!(out.contains("  --color-card: #0c0c0e;"));
    }

    #[test]
    fn z_index_renders_numeric_no_unit() {
        let mut d = minimal();
        d.z_indices.push(ZToken {
            name: "modal".to_owned(),
            value: 1300,
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --z-modal: 1300;"));
    }

    #[test]
    fn easing_cubic_bezier_preserved_verbatim() {
        let mut d = minimal();
        d.motion.easings.push(EasingToken {
            name: "out".to_owned(),
            value: "cubic-bezier(0, 0, 0.2, 1)".to_owned(),
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --easing-out: cubic-bezier(0, 0, 0.2, 1);"));
    }

    #[test]
    fn weight_emits_with_font_weight_prefix() {
        let mut d = minimal();
        d.typography.weights.push(WeightToken {
            name: "semibold".to_owned(),
            value: 600,
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --font-weight-semibold: 600;"));
    }

    #[test]
    fn tracking_renders_as_em_or_zero() {
        let mut d = minimal();
        d.typography.tracking.push(TrackingToken {
            name: "tight".to_owned(),
            value: "-0.025em".to_owned(),
        });
        d.typography.tracking.push(TrackingToken {
            name: "normal".to_owned(),
            value: "0".to_owned(),
        });
        let out = emit_tokens_css(&d);
        assert!(out.contains("  --tracking-tight: -0.025em;"));
        assert!(out.contains("  --tracking-normal: 0;"));
    }
}

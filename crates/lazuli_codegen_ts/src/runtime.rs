//! Runtime-form TS emitter — produces a TypeScript file structurally
//! identical to the hand-written `dist/web/customer/src/customer.gen.ts`.
//! Output consumes `@lazuli/runtime`: typed `Customer` interface, one
//! `defineCommand<I, O>(name, { invalidates })` per command, and one
//! `defineQuery<A, R>(name)` per query.
//!
//! Driven by `lazuli_codegen_spec::RuntimeFeature` so both this crate and
//! `lazuli_codegen_go` consume the same canonical spec.

use std::fmt::Write;

use lazuli_codegen_spec::{
    FieldKind, QueryKind, RuntimeArg, RuntimeCommand, RuntimeFeature, RuntimeQuery, RuntimeResource,
};
use lazuli_ir as ir;

use crate::lzx::{lower_camel as lzx_lower_camel, pascal_case as lzx_pascal_case};

/// Emit the canonical `<feature>.gen.ts` for a feature. The emitted source
/// matches the layout of `dist/web/customer/src/customer.gen.ts`.
pub fn emit_feature_ts(feature: &RuntimeFeature) -> String {
    let mut s = String::new();
    write_header(&mut s, feature);
    write_imports(&mut s);
    for resource in &feature.resources {
        write_resource(&mut s, resource);
    }
    for command in &feature.commands {
        write_command(&mut s, feature, command);
    }
    for query in &feature.queries {
        write_query(&mut s, feature, query);
    }
    s
}

/// Emit the lifecycle action-map footer for an IR feature SDK.
///
/// The runtime-spec projection has not yet gained `Resource.lifecycle`; this
/// helper keeps the TS lifecycle surface tied to the canonical IR shape and can
/// be appended by the IR-backed SDK emitter when that projection is wired.
pub fn emit_lifecycle_action_maps_ts(feature: &ir::Feature) -> String {
    let mut s = String::new();
    write_lifecycle_action_maps(&mut s, feature);
    s
}

// ----------------------------------------------------------------------------
// Header / imports
// ----------------------------------------------------------------------------

fn write_header(s: &mut String, feature: &RuntimeFeature) {
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(s, "//").ok();
    writeln!(
        s,
        "// Source: {} (feature `{}`)",
        feature.source_path, feature.name
    )
    .ok();
    writeln!(s, "//").ok();
    writeln!(
        s,
        "// This file is hand-written for the runtime spike. Once the runtime API"
    )
    .ok();
    writeln!(
        s,
        "// stabilises, `crates/lazuli_codegen_ts` produces files exactly like this"
    )
    .ok();
    writeln!(
        s,
        "// — types + typed command/query specs — alongside the Go file under"
    )
    .ok();
    writeln!(s, "// `dist/go/customer/customer.gen.go`.").ok();
    writeln!(s).ok();
}

fn write_imports(s: &mut String) {
    writeln!(s, "import {{").ok();
    writeln!(s, "  defineCommand,").ok();
    writeln!(s, "  defineQuery,").ok();
    writeln!(s, "  type ID,").ok();
    writeln!(s, "  type Time,").ok();
    writeln!(s, "}} from \"@lazuli/runtime\";").ok();
    writeln!(s).ok();
}

// ----------------------------------------------------------------------------
// Resource
// ----------------------------------------------------------------------------

fn write_resource(s: &mut String, resource: &RuntimeResource) {
    let pascal = pascal_case(&resource.name);

    write_section_banner(s, &[format!("Resource: {pascal}")]);

    writeln!(s, "export interface {pascal} {{").ok();
    writeln!(s, "  id: ID;").ok();
    writeln!(s, "  org_id: ID;").ok();
    for field in &resource.fields {
        writeln!(s, "  {}: {};", field.name, field_kind_ts(field.kind)).ok();
    }
    writeln!(s, "  created_at: Time;").ok();
    writeln!(s, "  updated_at: Time;").ok();
    if resource.soft_delete {
        writeln!(s, "  deleted_at?: Time | null;").ok();
    }
    writeln!(s, "}}").ok();
    writeln!(s).ok();
}

// ----------------------------------------------------------------------------
// Command
// ----------------------------------------------------------------------------

fn write_command(s: &mut String, feature: &RuntimeFeature, command: &RuntimeCommand) {
    let resource = feature
        .resources
        .first()
        .expect("runtime spec needs at least one resource");
    let resource_pascal = pascal_case(&resource.name);
    let qualified_name = format!("{}.{}", feature.name, command.short_name);
    let input_iface = command_input_struct_name(&command.short_name, &resource_pascal);
    let var_name = command_var_name(&command.short_name, &resource_pascal);

    write_section_banner(s, &[format!("Command: {qualified_name}")]);

    // Input interface keys follow the same convention as the hand-written
    // file: route-param commands (any `ID` input) keep PascalCase keys
    // because the Go runtime's `lazuli.FromInput("ID")` binds against the
    // Go struct field name. Pure body-input commands lowercase every key
    // (idiomatic JSON, what most external clients expect).
    let preserve_case = command.inputs.iter().any(|i| i.field_name == "ID");
    writeln!(s, "export interface {input_iface} {{").ok();
    for input in &command.inputs {
        let key = if preserve_case {
            input.field_name.clone()
        } else {
            input.field_name.to_ascii_lowercase()
        };
        writeln!(s, "  {}: {};", key, field_kind_ts(input.kind)).ok();
    }
    writeln!(s, "}}").ok();
    writeln!(s).ok();

    // defineCommand call.
    let invalidates_lit = format_string_array(&command.invalidates);
    if invalidates_lit.len() + qualified_name.len() < 60 {
        writeln!(
            s,
            "export const {var_name} = defineCommand<{input_iface}, {resource_pascal}>("
        )
        .ok();
        writeln!(s, "  \"{qualified_name}\",").ok();
        writeln!(s, "  {{").ok();
        writeln!(s, "    invalidates: {invalidates_lit},").ok();
        write_deprecated_spec(s, command, "    ");
        writeln!(s, "  }},").ok();
        writeln!(s, ");").ok();
    } else {
        writeln!(s, "export const {var_name} = defineCommand<").ok();
        writeln!(s, "  {input_iface},").ok();
        writeln!(s, "  {resource_pascal}").ok();
        writeln!(s, ">(\"{qualified_name}\", {{").ok();
        writeln!(s, "  invalidates: {invalidates_lit},").ok();
        write_deprecated_spec(s, command, "  ");
        writeln!(s, "}});").ok();
    }
    writeln!(s).ok();
}

fn write_deprecated_spec(s: &mut String, command: &RuntimeCommand, indent: &str) {
    let Some(dep) = &command.deprecated else {
        return;
    };
    writeln!(s, "{indent}deprecated: {{").ok();
    if let Some(since) = &dep.since {
        writeln!(s, "{indent}  since: \"{}\",", escape_ts_string(since)).ok();
    }
    if let Some(replacement) = &dep.replacement {
        writeln!(
            s,
            "{indent}  replacement: \"{}\",",
            escape_ts_string(replacement)
        )
        .ok();
    }
    if let Some(sunset) = &dep.sunset {
        writeln!(s, "{indent}  sunset: \"{}\",", escape_ts_string(sunset)).ok();
    }
    writeln!(s, "{indent}}},").ok();
}

fn escape_ts_string(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

// ----------------------------------------------------------------------------
// Query
// ----------------------------------------------------------------------------

fn write_query(s: &mut String, feature: &RuntimeFeature, query: &RuntimeQuery) {
    let resource = feature
        .resources
        .first()
        .expect("runtime spec needs at least one resource");
    let resource_pascal = pascal_case(&resource.name);
    let qualified_name = format!("{}.query.{}", feature.name, query.short_name);

    let (args_iface, var_name, return_type) = match query.kind {
        QueryKind::List => (
            format!("List{}sArgs", resource_pascal),
            format!("list{}s", resource_pascal),
            format!("{}[]", resource_pascal),
        ),
        QueryKind::Lookup => (
            format!("{}{}Args", resource_pascal, pascal_case(&query.short_name)),
            format!(
                "{}{}",
                lower_camel(&resource.name),
                pascal_case(&query.short_name)
            ),
            resource_pascal.clone(),
        ),
    };

    write_section_banner(s, &[format!("Query: {qualified_name}")]);

    writeln!(s, "export interface {args_iface} {{").ok();
    for arg in &query.args {
        write_query_arg(s, arg);
    }
    writeln!(s, "}}").ok();
    writeln!(s).ok();

    writeln!(
        s,
        "export const {var_name} = defineQuery<{args_iface}, {return_type}>("
    )
    .ok();
    writeln!(s, "  \"{qualified_name}\",").ok();
    writeln!(s, ");").ok();
    writeln!(s).ok();
}

fn write_query_arg(s: &mut String, arg: &RuntimeArg) {
    let key = if arg.field_name == "ID" {
        "id".to_owned()
    } else {
        arg.field_name.to_ascii_lowercase()
    };
    let suffix = if arg.optional { "?" } else { "" };
    writeln!(s, "  {key}{suffix}: {ty};", ty = field_kind_ts(arg.kind)).ok();
}

// ----------------------------------------------------------------------------
// Lifecycle action maps
// ----------------------------------------------------------------------------

fn write_lifecycle_action_maps(s: &mut String, feature: &ir::Feature) {
    let lifecycle_resources: Vec<&ir::Resource> = feature
        .resources
        .iter()
        .filter(|resource| resource.lifecycle.is_some())
        .collect();

    if lifecycle_resources.is_empty() {
        return;
    }

    write_section_banner(s, &["Lifecycle action maps".to_owned()]);
    writeln!(
        s,
        "// Auto-generated from lifecycle. Per docs/proposals/lifecycle-vocab.md §6.2."
    )
    .ok();

    for resource in lifecycle_resources {
        let lifecycle = resource
            .lifecycle
            .as_ref()
            .expect("filtered lifecycle resources have lifecycle");
        let resource_pascal = lzx_pascal_case(&resource.name);
        let object_name = resource.name.to_ascii_lowercase();
        writeln!(s, "export const {object_name} = {{").ok();
        for transition in &lifecycle.transitions {
            let action_key = lzx_lower_camel(&transition.name);
            let command_ident = lifecycle_command_ident(&transition.name, &resource_pascal);
            let input_type = lifecycle_transition_input_type(feature, &transition.name);
            writeln!(
                s,
                "  {action_key}: useLazuliCommand<{input_type}, void>({command_ident}),"
            )
            .ok();
        }
        writeln!(s, "}} as const;").ok();
        writeln!(s).ok();
    }
}

fn lifecycle_command_ident(transition_name: &str, resource_pascal: &str) -> String {
    format!("{}{resource_pascal}", lzx_lower_camel(transition_name))
}

fn lifecycle_transition_input_type(feature: &ir::Feature, transition_name: &str) -> String {
    let mut fields = vec![("id".to_owned(), "ID".to_owned())];

    if let Some(command) = feature
        .commands
        .iter()
        .find(|command| command.name == transition_name)
    {
        for route in &command.route {
            push_lifecycle_input_field(&mut fields, &route.name, &route.type_ref);
        }
        if let ir::CommandInput::Typed(slots) = &command.input {
            for slot in slots {
                push_lifecycle_input_field(&mut fields, &slot.name, &slot.type_ref);
            }
        }
    }

    let parts: Vec<String> = fields
        .into_iter()
        .map(|(name, ty)| format!("{name}: {ty}"))
        .collect();
    format!("{{ {} }}", parts.join("; "))
}

fn push_lifecycle_input_field(
    fields: &mut Vec<(String, String)>,
    name: &str,
    type_ref: &ir::TypeRef,
) {
    let key = if name.eq_ignore_ascii_case("id") {
        "id".to_owned()
    } else {
        lzx_lower_camel(name)
    };
    if fields.iter().any(|(existing, _)| existing == &key) {
        return;
    }
    fields.push((key, type_ref_ts(type_ref).to_owned()));
}

fn type_ref_ts(type_ref: &ir::TypeRef) -> &'static str {
    match type_ref {
        ir::TypeRef::Builtin(ir::BuiltinType::Id) => "ID",
        ir::TypeRef::Builtin(ir::BuiltinType::Boolean) => "boolean",
        ir::TypeRef::Builtin(ir::BuiltinType::Integer | ir::BuiltinType::Decimal) => "number",
        ir::TypeRef::Builtin(
            ir::BuiltinType::Text
            | ir::BuiltinType::Date
            | ir::BuiltinType::DateTime
            | ir::BuiltinType::SemanticEmail
            | ir::BuiltinType::SemanticMoney
            | ir::BuiltinType::SemanticPhone
            | ir::BuiltinType::SemanticUrl
            | ir::BuiltinType::SemanticUuid
            | ir::BuiltinType::SemanticCurrency
            | ir::BuiltinType::SemanticGeoPoint,
        ) => "string",
        ir::TypeRef::Builtin(ir::BuiltinType::Json) => "unknown",
        ir::TypeRef::Builtin(ir::BuiltinType::CapSecret | ir::BuiltinType::CapFile) => "unknown",
        ir::TypeRef::EnumRef(_) | ir::TypeRef::UserDefined(_) | ir::TypeRef::Unresolved(_) => {
            "string"
        }
        ir::TypeRef::Many(_) => "unknown[]",
        ir::TypeRef::Capability(_) => "unknown",
    }
}

// ----------------------------------------------------------------------------
// Helpers
// ----------------------------------------------------------------------------

fn write_section_banner(s: &mut String, lines: &[String]) {
    writeln!(s, "// {}", "-".repeat(76)).ok();
    for line in lines {
        writeln!(s, "// {line}").ok();
    }
    writeln!(s, "// {}", "-".repeat(76)).ok();
    writeln!(s).ok();
}

fn format_string_array(items: &[String]) -> String {
    if items.is_empty() {
        return "[]".to_owned();
    }
    let parts: Vec<String> = items.iter().map(|s| format!("\"{s}\"")).collect();
    format!("[{}]", parts.join(", "))
}

fn field_kind_ts(kind: FieldKind) -> &'static str {
    match kind {
        FieldKind::Text | FieldKind::Email => "string",
        FieldKind::Integer => "ID",
        FieldKind::Boolean => "boolean",
    }
}

fn pascal_case(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for word in s.split(|c: char| c == '_' || c == '-') {
        if word.is_empty() {
            continue;
        }
        if is_acronym(word) {
            out.push_str(&word.to_ascii_uppercase());
            continue;
        }
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            for u in first.to_uppercase() {
                out.push(u);
            }
        }
        out.push_str(chars.as_str());
    }
    out
}

fn lower_camel(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut first = true;
    for word in s.split(|c: char| c == '_' || c == '-') {
        if word.is_empty() {
            continue;
        }
        if first {
            out.push_str(&word.to_ascii_lowercase());
            first = false;
            continue;
        }
        if is_acronym(word) {
            out.push_str(&word.to_ascii_uppercase());
            continue;
        }
        let mut chars = word.chars();
        if let Some(c) = chars.next() {
            for u in c.to_uppercase() {
                out.push(u);
            }
        }
        out.push_str(chars.as_str());
    }
    out
}

fn is_acronym(word: &str) -> bool {
    matches!(
        word.to_ascii_lowercase().as_str(),
        "id" | "url" | "uri" | "api" | "html" | "json" | "sql" | "ttl"
    )
}

fn command_input_struct_name(short_name: &str, resource_pascal: &str) -> String {
    let mut parts = short_name.split('_');
    let verb = parts.next().unwrap_or("");
    let modifier_words: Vec<&str> = parts.collect();
    let mut out = pascal_case(verb);
    out.push_str(resource_pascal);
    for w in modifier_words {
        out.push_str(&pascal_case(w));
    }
    out.push_str("Input");
    out
}

fn command_var_name(short_name: &str, resource_pascal: &str) -> String {
    let mut parts = short_name.split('_');
    let verb = parts.next().unwrap_or("");
    let modifier_words: Vec<&str> = parts.collect();
    let mut out = verb.to_ascii_lowercase();
    out.push_str(resource_pascal);
    for w in modifier_words {
        out.push_str(&pascal_case(w));
    }
    out
}


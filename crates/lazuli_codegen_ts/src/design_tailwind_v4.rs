//! `tailwind.theme.css` emitter — Tailwind v4 `@theme { … }` block whose
//! members redirect back through CSS variables defined in `tokens.css`.
//! See `docs/proposals/design-tokens.md` §4.5.
//!
//! Per the proposal, the v4 emitter MUST re-verify the paired
//! `--text-<size>` / `--text-<size>--line-height` convention against Tailwind
//! v4 stable docs at codegen time. We follow the convention as shipped at
//! v4.0 (2025-01). If the convention changes, this emitter is the single
//! location to update.
//!
//! Key mappings (v4 token naming, from the proposal example):
//!   - color (single Base)    → `--color-<name>: var(--color-<name>);`
//!   - color (multi-state)    → `--color-<name>: var(--color-<name>-base);`
//!                              plus `--color-<name>-<state>` for each state.
//!   - font.family.<n>        → `--font-<n>: var(--font-<n>);`
//!   - typography.scale       → `--text-<n>: var(--text-<n>); --text-<n>--line-height: …`
//!   - space.<n>              → `--spacing-<n>: var(--space-<n>);` (v4 calls it `spacing`).
//!   - radius.<n>             → `--radius-<n>: var(--radius-<n>);`
//!   - shadow.<n>             → `--shadow-<n>: var(--shadow-<n>);`
//!   - motion.duration.<n>    → `--duration-<n>: var(--duration-<n>);`
//!   - motion.easing.<n>      → `--ease-<n>: var(--easing-<n>);` (v4 calls the
//!                              utility group `ease-…`, the source var keeps
//!                              the `--easing-` prefix from tokens.css).
//!   - breakpoint.<n>         → `--breakpoint-<n>: <raw-px>;` (Tailwind v4
//!                              consumes the literal value directly so users
//!                              can author `@media (min-width: theme(…))`).
//!   - z.<n>                  → `--z-<n>: var(--z-<n>);`

use std::fmt::Write;

use super::ir::{ColorStateKind, ColorToken, Design};

/// Emit `dist/ts-web/design/tailwind.theme.css` for the given `Design`.
pub fn emit_tailwind_v4_theme(design: &Design) -> String {
    let mut s = String::new();
    writeln!(s, "/* Code generated by lazuli; DO NOT EDIT. */").ok();
    writeln!(s, "/* Source: design.lzi (design `{}`) */", design.name).ok();
    writeln!(s, "@import \"./tokens.css\";").ok();
    writeln!(s).ok();
    writeln!(s, "@theme {{").ok();

    // colors
    for color in &design.colors {
        emit_color(&mut s, color);
    }
    // Custom tokens (9th meta-group) — emit flat `--color-<n>` aliases so
    // Tailwind v4's utility-class generator sees them alongside the
    // Shadcn-semantic palette. See
    // `docs/proposals/design-tokens-custom.md` §5.
    for tok in &design.custom {
        let n = kebab(&tok.name);
        writeln!(s, "  --color-{}: var(--color-{});", n, n).ok();
    }
    if !design.colors.is_empty() || !design.custom.is_empty() {
        writeln!(s).ok();
    }

    // font families
    for fam in &design.typography.families {
        let n = kebab(&fam.name);
        writeln!(s, "  --font-{}: var(--font-{});", n, n).ok();
    }
    if !design.typography.families.is_empty() {
        writeln!(s).ok();
    }

    // typography scale
    for entry in &design.typography.scale {
        let n = kebab(&entry.name);
        writeln!(s, "  --text-{}: var(--text-{});", n, n).ok();
        writeln!(
            s,
            "  --text-{}--line-height: var(--text-{}--line-height);",
            n, n
        )
        .ok();
    }
    if !design.typography.scale.is_empty() {
        writeln!(s).ok();
    }

    // weight (v4 calls the utility group `font-weight-…`).
    for w in &design.typography.weights {
        let n = kebab(&w.name);
        writeln!(s, "  --font-weight-{}: var(--font-weight-{});", n, n).ok();
    }
    if !design.typography.weights.is_empty() {
        writeln!(s).ok();
    }

    // tracking
    for t in &design.typography.tracking {
        let n = kebab(&t.name);
        writeln!(s, "  --tracking-{}: var(--tracking-{});", n, n).ok();
    }
    if !design.typography.tracking.is_empty() {
        writeln!(s).ok();
    }

    // space → spacing
    for tok in &design.spaces {
        let n = kebab(&tok.name);
        writeln!(s, "  --spacing-{}: var(--space-{});", n, n).ok();
    }
    if !design.spaces.is_empty() {
        writeln!(s).ok();
    }

    // radius
    for tok in &design.radii {
        let n = kebab(&tok.name);
        writeln!(s, "  --radius-{}: var(--radius-{});", n, n).ok();
    }
    if !design.radii.is_empty() {
        writeln!(s).ok();
    }

    // shadow
    for tok in &design.shadows {
        let n = kebab(&tok.name);
        writeln!(s, "  --shadow-{}: var(--shadow-{});", n, n).ok();
    }
    if !design.shadows.is_empty() {
        writeln!(s).ok();
    }

    // duration
    for d in &design.motion.durations {
        let n = kebab(&d.name);
        writeln!(s, "  --duration-{}: var(--duration-{});", n, n).ok();
    }
    if !design.motion.durations.is_empty() {
        writeln!(s).ok();
    }

    // easing → v4 utility key is `ease`, source var keeps `--easing-`
    for e in &design.motion.easings {
        let n = kebab(&e.name);
        writeln!(s, "  --ease-{}: var(--easing-{});", n, n).ok();
    }
    if !design.motion.easings.is_empty() {
        writeln!(s).ok();
    }

    // breakpoint — v4 reads literal values to compose media queries.
    for tok in &design.breakpoints {
        let n = kebab(&tok.name);
        writeln!(s, "  --breakpoint-{}: {};", n, tok.value).ok();
    }
    if !design.breakpoints.is_empty() {
        writeln!(s).ok();
    }

    // z
    for tok in &design.z_indices {
        let n = kebab(&tok.name);
        writeln!(s, "  --z-{}: var(--z-{});", n, n).ok();
    }

    writeln!(s, "}}").ok();
    s
}

fn emit_color(s: &mut String, color: &ColorToken) {
    let n = kebab(&color.name);
    let single_base = color.states.len() == 1
        && color.states.first().map(|st| st.kind) == Some(ColorStateKind::Base);
    if single_base {
        writeln!(s, "  --color-{}: var(--color-{});", n, n).ok();
        return;
    }
    // multi-state: emit a top-level `--color-<name>` aliasing the base, plus
    // per-state vars.
    let has_base = color
        .states
        .iter()
        .any(|st| st.kind == ColorStateKind::Base);
    if has_base {
        writeln!(s, "  --color-{}: var(--color-{}-base);", n, n).ok();
    }
    for state in &color.states {
        let suffix = state_kind_suffix(state.kind);
        writeln!(
            s,
            "  --color-{}-{}: var(--color-{}-{});",
            n, suffix, n, suffix
        )
        .ok();
    }
}

fn state_kind_suffix(kind: ColorStateKind) -> &'static str {
    match kind {
        ColorStateKind::Base => "base",
        ColorStateKind::Hover => "hover",
        ColorStateKind::Active => "active",
        ColorStateKind::Foreground => "foreground",
    }
}

fn kebab(s: &str) -> String {
    s.chars()
        .map(|c| if c == '_' || c == ' ' { '-' } else { c })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::design::ir::{
        ColorState, ColorStateKind, ColorToken, Design, EasingToken, FamilyToken, Motion,
        ScaleToken, ShadowToken, TextScaleToken, Typography, WeightToken, ZToken,
    };

    fn minimal() -> Design {
        Design {
            name: "tiny".to_owned(),
            extends: None,
            colors: vec![ColorToken {
                name: "success".to_owned(),
                states: vec![ColorState {
                    kind: ColorStateKind::Base,
                    value: "#16a34a".to_owned(),
                    dark: None,
                }],
                span_ref: None,
            }],
            typography: Typography {
                families: vec![FamilyToken {
                    name: "sans".to_owned(),
                    value: "Inter, system-ui, sans-serif".to_owned(),
                }],
                scale: vec![TextScaleToken {
                    name: "base".to_owned(),
                    size: "1rem".to_owned(),
                    line_height: "1.5rem".to_owned(),
                }],
                weights: vec![],
                tracking: vec![],
            },
            spaces: vec![ScaleToken {
                name: "4".to_owned(),
                value: "1rem".to_owned(),
            }],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            custom: vec![],
            span_ref: None,
        }
    }

    #[test]
    fn minimal_emits_at_theme_block_and_tokens_import() {
        let out = emit_tailwind_v4_theme(&minimal());
        assert!(out.starts_with("/* Code generated by lazuli; DO NOT EDIT. */"));
        assert!(out.contains("@import \"./tokens.css\";"));
        assert!(out.contains("@theme {"));
        assert!(out.contains("  --color-success: var(--color-success);"));
        assert!(out.contains("  --font-sans: var(--font-sans);"));
        assert!(out.contains("  --text-base: var(--text-base);"));
        assert!(out.contains("  --text-base--line-height: var(--text-base--line-height);"));
        assert!(out.contains("  --spacing-4: var(--space-4);"));
        assert!(out.trim_end().ends_with("}"));
    }

    #[test]
    fn multi_state_color_emits_default_alias_and_states() {
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "primary".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#7c3aed".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Hover,
                    value: "#6d28d9".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Foreground,
                    value: "#ffffff".to_owned(),
                    dark: None,
                },
            ],
            span_ref: None,
        });
        let out = emit_tailwind_v4_theme(&d);
        assert!(out.contains("  --color-primary: var(--color-primary-base);"));
        assert!(out.contains("  --color-primary-base: var(--color-primary-base);"));
        assert!(out.contains("  --color-primary-hover: var(--color-primary-hover);"));
        assert!(out.contains("  --color-primary-foreground: var(--color-primary-foreground);"));
    }

    #[test]
    fn dark_color_keeps_theme_block_pointing_to_vars() {
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "background".to_owned(),
            states: vec![ColorState {
                kind: ColorStateKind::Base,
                value: "#ffffff".to_owned(),
                dark: Some("#09090b".to_owned()),
            }],
            span_ref: None,
        });
        let out = emit_tailwind_v4_theme(&d);
        // No hex inlined here — dark/light swap happens in tokens.css.
        assert!(!out.contains("#09090b"));
        assert!(!out.contains("#ffffff"));
        assert!(out.contains("  --color-background: var(--color-background);"));
    }

    #[test]
    fn empty_design_still_emits_theme_skeleton() {
        let d = Design {
            name: "void".to_owned(),
            extends: None,
            colors: vec![],
            typography: Typography::default(),
            spaces: vec![],
            radii: vec![],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![],
            z_indices: vec![],
            custom: vec![],
            span_ref: None,
        };
        let out = emit_tailwind_v4_theme(&d);
        assert!(out.contains("@theme {"));
        assert!(out.trim_end().ends_with("}"));
    }

    #[test]
    fn breakpoint_emits_literal_value_not_var() {
        let mut d = minimal();
        d.breakpoints.push(ScaleToken {
            name: "md".to_owned(),
            value: "768px".to_owned(),
        });
        let out = emit_tailwind_v4_theme(&d);
        // Breakpoints emit literal values per proposal §4.5.
        assert!(out.contains("  --breakpoint-md: 768px;"));
    }

    #[test]
    fn easing_uses_ease_prefix() {
        let mut d = minimal();
        d.motion.easings.push(EasingToken {
            name: "out".to_owned(),
            value: "cubic-bezier(0, 0, 0.2, 1)".to_owned(),
        });
        let out = emit_tailwind_v4_theme(&d);
        // v4 utility group is `ease`, source var keeps `--easing-` from tokens.css.
        assert!(out.contains("  --ease-out: var(--easing-out);"));
    }

    #[test]
    fn shadow_emits_var_reference() {
        let mut d = minimal();
        d.shadows.push(ShadowToken {
            name: "md".to_owned(),
            value: "0 4px 6px -1px rgb(0 0 0 / 0.1)".to_owned(),
        });
        let out = emit_tailwind_v4_theme(&d);
        assert!(out.contains("  --shadow-md: var(--shadow-md);"));
        // The actual value lives in tokens.css; v4 theme just routes.
        assert!(!out.contains("0 4px 6px"));
    }

    #[test]
    fn weight_uses_font_weight_prefix() {
        let mut d = minimal();
        d.typography.weights.push(WeightToken {
            name: "bold".to_owned(),
            value: 700,
        });
        let out = emit_tailwind_v4_theme(&d);
        assert!(out.contains("  --font-weight-bold: var(--font-weight-bold);"));
    }

    #[test]
    fn z_index_uses_z_prefix() {
        let mut d = minimal();
        d.z_indices.push(ZToken {
            name: "modal".to_owned(),
            value: 1300,
        });
        let out = emit_tailwind_v4_theme(&d);
        assert!(out.contains("  --z-modal: var(--z-modal);"));
    }
}

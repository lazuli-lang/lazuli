//! `tailwind.gen.ts` emitter — Tailwind v3 `Partial<Config>` preset whose
//! colors are wired back through CSS variables (so `data-theme="dark"` swaps
//! work without Tailwind re-parsing classes). See `docs/proposals/
//! design-tokens.md` §4.4.
//!
//! Key mappings:
//! - Single-Base color           → `name: "var(--color-name)"`.
//! - Multi-state color (no dark) → `name: { DEFAULT: "var(--color-name-base)", hover: ..., ... }`.
//! - Color with dark             → still routed via `var(--color-…)` — the
//!   dark swap lives in the CSS layer, the preset shape is identical.
//! - `radius.base`               → emitted as `DEFAULT` (Tailwind's
//!   `border-radius` default key).
//! - `motion.duration.base`      → emitted as `DEFAULT` for
//!   `transitionDuration` (same convention).

use std::fmt::Write;

use super::ir::{ColorStateKind, ColorToken, Design};

/// Emit `dist/ts-web/design/tailwind.gen.ts` for the given `Design`.
pub fn emit_tailwind_v3_preset(design: &Design) -> String {
    let mut s = String::new();
    writeln!(s, "// Code generated by lazuli; DO NOT EDIT.").ok();
    writeln!(s, "// Source: design.lzi (design `{}`)", design.name).ok();
    writeln!(s, "import type {{ Config }} from \"tailwindcss\";").ok();
    writeln!(s).ok();
    writeln!(s, "export const lazuliPreset: Partial<Config> = {{").ok();
    writeln!(s, "  darkMode: [\"class\", '[data-theme=\"dark\"]'],").ok();
    writeln!(s, "  theme: {{").ok();
    writeln!(s, "    extend: {{").ok();

    // colors
    writeln!(s, "      colors: {{").ok();
    for color in &design.colors {
        emit_color(&mut s, color);
    }
    writeln!(s, "      }},").ok();

    // fontFamily
    writeln!(s, "      fontFamily: {{").ok();
    for fam in &design.typography.families {
        writeln!(
            s,
            "        {}: \"var(--font-{})\",",
            quote_key(&fam.name),
            kebab(&fam.name)
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // fontSize
    writeln!(s, "      fontSize: {{").ok();
    for entry in &design.typography.scale {
        writeln!(
            s,
            "        {}: [{}, {{ lineHeight: {} }}],",
            quote_key(&entry.name),
            ts_string(&entry.size),
            ts_string(&entry.line_height),
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // fontWeight (Tailwind expects string values per v3 docs).
    writeln!(s, "      fontWeight: {{").ok();
    for w in &design.typography.weights {
        writeln!(s, "        {}: \"{}\",", quote_key(&w.name), w.value).ok();
    }
    writeln!(s, "      }},").ok();

    // letterSpacing
    writeln!(s, "      letterSpacing: {{").ok();
    for t in &design.typography.tracking {
        writeln!(
            s,
            "        {}: {},",
            quote_key(&t.name),
            ts_string(&t.value)
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // spacing
    writeln!(s, "      spacing: {{").ok();
    for tok in &design.spaces {
        writeln!(
            s,
            "        {}: {},",
            quote_key(&tok.name),
            ts_string(&tok.value)
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // borderRadius (radius.base → DEFAULT).
    writeln!(s, "      borderRadius: {{").ok();
    for tok in &design.radii {
        let key = if tok.name == "base" {
            "DEFAULT".to_owned()
        } else {
            quote_key(&tok.name)
        };
        writeln!(s, "        {}: {},", key, ts_string(&tok.value)).ok();
    }
    writeln!(s, "      }},").ok();

    // boxShadow
    writeln!(s, "      boxShadow: {{").ok();
    for tok in &design.shadows {
        let key = if tok.name == "base" {
            "DEFAULT".to_owned()
        } else {
            quote_key(&tok.name)
        };
        writeln!(s, "        {}: {},", key, ts_string(&tok.value)).ok();
    }
    writeln!(s, "      }},").ok();

    // transitionDuration (motion.duration.base → DEFAULT).
    writeln!(s, "      transitionDuration: {{").ok();
    for d in &design.motion.durations {
        let key = if d.name == "base" {
            "DEFAULT".to_owned()
        } else {
            quote_key(&d.name)
        };
        writeln!(s, "        {}: {},", key, ts_string(&d.value)).ok();
    }
    writeln!(s, "      }},").ok();

    // transitionTimingFunction
    writeln!(s, "      transitionTimingFunction: {{").ok();
    for e in &design.motion.easings {
        writeln!(
            s,
            "        {}: {},",
            quote_key(&e.name),
            ts_string(&e.value)
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // screens (breakpoints)
    writeln!(s, "      screens: {{").ok();
    for tok in &design.breakpoints {
        writeln!(
            s,
            "        {}: {},",
            quote_key(&tok.name),
            ts_string(&tok.value)
        )
        .ok();
    }
    writeln!(s, "      }},").ok();

    // zIndex (Tailwind v3 expects string).
    writeln!(s, "      zIndex: {{").ok();
    for tok in &design.z_indices {
        writeln!(s, "        {}: \"{}\",", quote_key(&tok.name), tok.value).ok();
    }
    writeln!(s, "      }},").ok();

    writeln!(s, "    }},").ok();
    writeln!(s, "  }},").ok();
    writeln!(s, "}};").ok();
    s
}

fn emit_color(s: &mut String, color: &ColorToken) {
    let key = quote_key(&color.name);
    let single_base = color.states.len() == 1
        && color.states.first().map(|st| st.kind) == Some(ColorStateKind::Base);
    let group = kebab(&color.name);
    if single_base {
        // Flat var reference.
        writeln!(s, "        {}: \"var(--color-{})\",", key, group).ok();
        return;
    }
    writeln!(s, "        {}: {{", key).ok();
    for state in &color.states {
        let suffix = state_kind_suffix(state.kind);
        let nested_key = if state.kind == ColorStateKind::Base {
            "DEFAULT".to_owned()
        } else {
            suffix.to_owned()
        };
        writeln!(
            s,
            "          {}: \"var(--color-{}-{})\",",
            nested_key, group, suffix
        )
        .ok();
    }
    writeln!(s, "        }},").ok();
}

fn state_kind_suffix(kind: ColorStateKind) -> &'static str {
    match kind {
        ColorStateKind::Base => "base",
        ColorStateKind::Hover => "hover",
        ColorStateKind::Active => "active",
        ColorStateKind::Foreground => "foreground",
    }
}

fn kebab(s: &str) -> String {
    s.chars()
        .map(|c| if c == '_' || c == ' ' { '-' } else { c })
        .collect()
}

fn quote_key(name: &str) -> String {
    if is_safe_ident(name) {
        name.to_owned()
    } else {
        format!("\"{}\"", escape_string(name))
    }
}

fn is_safe_ident(s: &str) -> bool {
    let mut it = s.chars();
    match it.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }
    it.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn ts_string(value: &str) -> String {
    format!("\"{}\"", escape_string(value))
}

fn escape_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::design::ir::{
        ColorState, ColorStateKind, ColorToken, Design, EasingToken, FamilyToken, Motion,
        ScaleToken, ShadowToken, TextScaleToken, TrackingToken, Typography, WeightToken, ZToken,
    };

    fn minimal() -> Design {
        Design {
            name: "tiny".to_owned(),
            extends: None,
            colors: vec![ColorToken {
                name: "success".to_owned(),
                states: vec![ColorState {
                    kind: ColorStateKind::Base,
                    value: "#16a34a".to_owned(),
                    dark: None,
                }],
                span_ref: None,
            }],
            typography: Typography {
                families: vec![FamilyToken {
                    name: "sans".to_owned(),
                    value: "Inter, system-ui, sans-serif".to_owned(),
                }],
                scale: vec![TextScaleToken {
                    name: "base".to_owned(),
                    size: "1rem".to_owned(),
                    line_height: "1.5rem".to_owned(),
                }],
                weights: vec![],
                tracking: vec![],
            },
            spaces: vec![ScaleToken {
                name: "4".to_owned(),
                value: "1rem".to_owned(),
            }],
            radii: vec![ScaleToken {
                name: "base".to_owned(),
                value: "0.25rem".to_owned(),
            }],
            shadows: vec![],
            motion: Motion::default(),
            breakpoints: vec![ScaleToken {
                name: "sm".to_owned(),
                value: "640px".to_owned(),
            }],
            z_indices: vec![ZToken {
                name: "modal".to_owned(),
                value: 1300,
            }],
            span_ref: None,
        }
    }

    #[test]
    fn minimal_fixture_emits_preset_structure() {
        let out = emit_tailwind_v3_preset(&minimal());
        assert!(out.contains("import type { Config } from \"tailwindcss\";"));
        assert!(out.contains("export const lazuliPreset: Partial<Config> = {"));
        assert!(out.contains("darkMode: [\"class\", '[data-theme=\"dark\"]'],"));
        assert!(out.contains("colors: {"));
        assert!(out.contains("success: \"var(--color-success)\","));
        // radius.base → DEFAULT
        assert!(out.contains("DEFAULT: \"0.25rem\","));
        // zIndex strings
        assert!(out.contains("modal: \"1300\","));
        assert!(out.contains("sm: \"640px\","));
    }

    #[test]
    fn multi_state_color_emits_default_plus_states() {
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "primary".to_owned(),
            states: vec![
                ColorState {
                    kind: ColorStateKind::Base,
                    value: "#7c3aed".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Hover,
                    value: "#6d28d9".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Active,
                    value: "#5b21b6".to_owned(),
                    dark: None,
                },
                ColorState {
                    kind: ColorStateKind::Foreground,
                    value: "#ffffff".to_owned(),
                    dark: None,
                },
            ],
            span_ref: None,
        });
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("primary: {"));
        assert!(out.contains("DEFAULT: \"var(--color-primary-base)\","));
        assert!(out.contains("hover: \"var(--color-primary-hover)\","));
        assert!(out.contains("active: \"var(--color-primary-active)\","));
        assert!(out.contains("foreground: \"var(--color-primary-foreground)\","));
    }

    #[test]
    fn dark_variant_preset_does_not_inline_dark_hex() {
        // Dark variants live in tokens.css; the preset stays var-backed.
        let mut d = minimal();
        d.colors.push(ColorToken {
            name: "background".to_owned(),
            states: vec![ColorState {
                kind: ColorStateKind::Base,
                value: "#ffffff".to_owned(),
                dark: Some("#09090b".to_owned()),
            }],
            span_ref: None,
        });
        let out = emit_tailwind_v3_preset(&d);
        // The preset must reference the variable, NOT inline either hex.
        assert!(out.contains("background: \"var(--color-background)\","));
        assert!(!out.contains("#09090b"));
        assert!(!out.contains("#ffffff"));
    }

    #[test]
    fn empty_motion_easings_emits_empty_block() {
        let d = minimal();
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("transitionTimingFunction: {"));
        // Must close the block even when empty.
        assert!(out.contains("transitionTimingFunction: {\n      },"));
    }

    #[test]
    fn shadow_base_maps_to_default() {
        let mut d = minimal();
        d.shadows.push(ShadowToken {
            name: "base".to_owned(),
            value: "0 1px 3px 0 rgb(0 0 0 / 0.1)".to_owned(),
        });
        d.shadows.push(ShadowToken {
            name: "md".to_owned(),
            value: "0 4px 6px -1px rgb(0 0 0 / 0.1)".to_owned(),
        });
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("DEFAULT: \"0 1px 3px 0 rgb(0 0 0 / 0.1)\","));
        assert!(out.contains("md: \"0 4px 6px -1px rgb(0 0 0 / 0.1)\","));
    }

    #[test]
    fn motion_base_duration_maps_to_default() {
        let mut d = minimal();
        d.motion.durations.push(ScaleToken {
            name: "fast".to_owned(),
            value: "150ms".to_owned(),
        });
        d.motion.durations.push(ScaleToken {
            name: "base".to_owned(),
            value: "200ms".to_owned(),
        });
        d.motion.easings.push(EasingToken {
            name: "out".to_owned(),
            value: "cubic-bezier(0, 0, 0.2, 1)".to_owned(),
        });
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("transitionDuration: {"));
        assert!(out.contains("fast: \"150ms\","));
        assert!(out.contains("DEFAULT: \"200ms\","));
        assert!(out.contains("out: \"cubic-bezier(0, 0, 0.2, 1)\","));
    }

    #[test]
    fn font_weight_emitted_as_string_not_number() {
        let mut d = minimal();
        d.typography.weights.push(WeightToken {
            name: "semibold".to_owned(),
            value: 600,
        });
        let out = emit_tailwind_v3_preset(&d);
        // Tailwind v3 expects string values for fontWeight.
        assert!(out.contains("semibold: \"600\","));
    }

    #[test]
    fn letter_spacing_uses_tracking_values() {
        let mut d = minimal();
        d.typography.tracking.push(TrackingToken {
            name: "tight".to_owned(),
            value: "-0.025em".to_owned(),
        });
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("letterSpacing: {"));
        assert!(out.contains("tight: \"-0.025em\","));
    }

    #[test]
    fn quoted_scale_name_is_preserved_in_font_size() {
        let mut d = minimal();
        d.typography.scale.push(TextScaleToken {
            name: "2xl".to_owned(),
            size: "1.5rem".to_owned(),
            line_height: "2rem".to_owned(),
        });
        let out = emit_tailwind_v3_preset(&d);
        assert!(out.contains("\"2xl\": [\"1.5rem\", { lineHeight: \"2rem\" }],"));
    }
}

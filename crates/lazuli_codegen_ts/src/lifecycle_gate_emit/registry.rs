//! `dist/<target>/app/lifecycle_gates.gen.ts` — single aggregate
//! registry of every gate in the module, keyed by view name.
//!
//! Consumers (today: hand-written app entry shells; later: an
//! orchestrator generator) read the registry to enumerate which
//! views are gated and what state/substep they expect.
//!
//! Dedup is `view_name`-keyed because the same view can be reached
//! through multiple `(feature, platform, audience)` triples in
//! multi-surface apps, and the registry is a flat lookup table.

use std::fmt::Write;

use crate::lzx::lzx_router_adapter::lifecycle_gate_pattern_header;

use super::LifecycleGate;
use super::helpers::ts_string;

pub(super) fn emit_registry_file(gates: &[LifecycleGate]) -> String {
    let mut s = String::new();
    s.push_str("// Code generated by lazuli; DO NOT EDIT.\n");
    s.push_str(&lifecycle_gate_pattern_header());
    writeln!(s, "export const lifecycleGates = {{").ok();
    let mut sorted = gates.to_vec();
    sorted.sort_by(|a, b| a.view_name.cmp(&b.view_name));
    sorted.dedup_by(|a, b| a.view_name == b.view_name);
    for gate in sorted {
        if let Some(substep) = &gate.expected_substep {
            writeln!(
                s,
                "  {}: {{ resource: {}, state: {}, substep: {}, resume: {} }},",
                ts_string(&gate.view_name),
                ts_string(&gate.resource),
                ts_string(&gate.expected_state),
                ts_string(substep),
                ts_string(&gate.resume_name)
            )
            .ok();
        } else {
            writeln!(
                s,
                "  {}: {{ resource: {}, state: {}, resume: {} }},",
                ts_string(&gate.view_name),
                ts_string(&gate.resource),
                ts_string(&gate.expected_state),
                ts_string(&gate.resume_name)
            )
            .ok();
        }
    }
    writeln!(s, "}} as const;").ok();
    s
}

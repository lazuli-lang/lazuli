//! Root `main.go` + manifest-plugin emit tests.
//!
//! Cell I2 invariants: every module materialises a `package main`
//! entry-point with sorted feature imports + a `lazuli.Boot` call,
//! and a `LazuriteManifest` toggles the dist-go submodule shape +
//! anonymous plugin imports.

use lazuli_codegen_go::{
    GoEmitOptions, LazuriteGenerateGo, generate_v1, generate_v1_with_manifest,
};

use super::builders::{empty_feature, lazurite_manifest, minimal_module};

#[test]
fn root_main_go_is_emitted_with_package_main_and_boot_call() {
    // Cell I2 integration smoke — every module materialises a root
    // `main.go` with a `package main` directive and the `lazuli.Boot`
    // call so `go build ./...` links a binary. Proven by the spike's
    // `dist/go/main.go`; the emitter now lifts that shape from raw
    // hand-written into deterministic codegen output.
    let module = minimal_module("test_app", "customer");
    let files = generate_v1(&module, &GoEmitOptions::default());
    let main = files
        .iter()
        .find(|f| f.path == "main.go")
        .expect("expected root main.go alongside go.mod");

    assert!(
        main.contents
            .contains("// Code generated by lazuli; DO NOT EDIT."),
        "missing Code Connect-style banner in main.go:\n{}",
        main.contents
    );
    assert!(
        main.contents.contains("\npackage main\n"),
        "expected `package main` in main.go:\n{}",
        main.contents
    );
    assert!(
        main.contents.contains("lazuli.Boot(ctx, dbURL)"),
        "expected `lazuli.Boot(ctx, dbURL)` invocation in main.go:\n{}",
        main.contents
    );
    // Feature side-effect import flips `init()` registrations on at
    // process start. `_` alias prevents Go's unused-import check from
    // failing the build.
    assert!(
        main.contents.contains("_ \"lazuli/test-app/customer\""),
        "expected side-effect feature import in main.go:\n{}",
        main.contents
    );
}

#[test]
fn root_main_go_sorts_feature_imports_lexicographically() {
    // Cell I2 invariant — feature side-effect imports walk the IR via
    // a `BTreeMap`, so the prelude is byte-stable regardless of how
    // the IR `Vec` happened to be populated.
    let mut module = minimal_module("marketplace", "zebra");
    module.features.push(empty_feature("alpha"));
    module.features.push(empty_feature("mango"));
    let files = generate_v1(&module, &GoEmitOptions::default());
    let main = files
        .iter()
        .find(|f| f.path == "main.go")
        .expect("expected root main.go");

    let alpha = main
        .contents
        .find("\"lazuli/marketplace/alpha\"")
        .expect("alpha import present");
    let mango = main
        .contents
        .find("\"lazuli/marketplace/mango\"")
        .expect("mango import present");
    let zebra = main
        .contents
        .find("\"lazuli/marketplace/zebra\"")
        .expect("zebra import present");
    assert!(
        alpha < mango && mango < zebra,
        "expected alpha < mango < zebra order, got positions {alpha}/{mango}/{zebra}"
    );
}

#[test]
fn emit_v1_with_manifest_plugins_emits_anonymous_imports() {
    let module = minimal_module("test_app", "customer");
    let manifest = lazurite_manifest(
        vec![
            (
                "@lazuli/plugin-mercadopago",
                "github.com/lazuli-lang/lazuli-plugin-mercadopago",
            ),
            (
                "@lazuli/plugin-expo_push",
                "github.com/lazuli-lang/lazuli-plugin-expo-push",
            ),
        ],
        Some(LazuriteGenerateGo {
            emit_main: true,
            submodule: true,
            dev_replace: None,
            dev_work_replace: None,
        }),
        Vec::new(),
    );
    let files = generate_v1_with_manifest(&module, &GoEmitOptions::default(), Some(&manifest));
    let main = files
        .iter()
        .find(|f| f.path == "main.go")
        .expect("expected main.go");

    let expo = main
        .contents
        .find("_ \"github.com/lazuli-lang/lazuli-plugin-expo-push\"")
        .expect("expo push plugin import");
    let mercado = main
        .contents
        .find("_ \"github.com/lazuli-lang/lazuli-plugin-mercadopago\"")
        .expect("mercadopago plugin import");
    assert!(expo < mercado, "expected plugin imports sorted by ref");
    assert!(
        main.contents
            .contains("// Plugin imports — side-effect aliases so each plugin's package")
    );
    assert!(main.contents.contains("init order across plugins"));
}

#[test]
fn emit_v1_with_submodule_false_skips_dist_go_mod() {
    let module = minimal_module("test_app", "customer");
    let manifest = lazurite_manifest(
        Vec::new(),
        Some(LazuriteGenerateGo {
            emit_main: true,
            submodule: false,
            dev_replace: None,
            dev_work_replace: None,
        }),
        Vec::new(),
    );
    let files = generate_v1_with_manifest(&module, &GoEmitOptions::default(), Some(&manifest));

    assert!(
        files.iter().all(|f| f.path != "go.mod"),
        "expected no dist/go/go.mod when submodule=false, got {:?}",
        files.iter().map(|f| &f.path).collect::<Vec<_>>()
    );
    assert!(
        files.iter().all(|f| f.path != "go.work"),
        "expected no go.work when submodule=false"
    );
}


//! `DROP TABLE` + companion commented `DROP INDEX` emission for the
//! per-resource down migration.
//!
//! The down migration mirrors the structure of the up migration:
//!
//! 1. Header comment block (`-- rollback for <feature>.<resource>`)
//! 2. `DROP TABLE IF EXISTS <table>;`
//! 3. Operator notes about cross-feature FK ordering + `postgis`
//!    extension lifecycle (the extension stays installed by design —
//!    extension removal is operational, not migration-driven).
//! 4. Commented `-- DROP INDEX` hints for the GIST/GIN/authored
//!    indexes that get implicitly dropped with the table but might
//!    need an explicit clean-reload step.
//!
//! Indexes are commented (not live SQL) because `DROP TABLE` already
//! removes them — the lines exist so operators dropping indexes ahead
//! of a clean reload have copy-pasteable commands.

use std::fmt::Write;

use lazuli_ir::{Constraint, Feature, Field, Resource};

use super::index::authored_index_name;
use super::sql_builder::{comment_value, is_direct_geo_point, lower_snake, quote_ident, sql_ident};
use crate::GeneratedFile;

pub(super) fn emit_resource_down_migration(feature: &Feature, resource: &Resource) -> String {
    let table_name = lower_snake(&resource.name);
    let geo_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| is_direct_geo_point(&field.type_ref))
        .collect();
    let full_text_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| field.full_text)
        .collect();

    let mut sql = String::new();
    let _ = writeln!(sql, "-- Code generated by lazuli; DO NOT EDIT.");
    let _ = writeln!(
        sql,
        "-- rollback for {}.{}",
        comment_value(&feature.name),
        comment_value(&resource.name)
    );
    let _ = writeln!(sql);
    let _ = writeln!(sql, "DROP TABLE IF EXISTS {};", quote_ident(&table_name));
    let _ = writeln!(
        sql,
        "-- Note: cross-feature FK columns rely on parent feature's down migration"
    );
    let _ = writeln!(
        sql,
        "-- to drop their target. Run rollbacks in reverse order if cascading."
    );

    if !geo_fields.is_empty() {
        let _ = writeln!(sql);
        for field in geo_fields {
            let _ = writeln!(
                sql,
                "-- DROP INDEX {};",
                sql_ident(&format!("{}_{}_gist", table_name, field.name))
            );
        }
        let _ = writeln!(
            sql,
            "-- Note: `CREATE EXTENSION postgis` is NOT dropped here \u{2014} extension"
        );
        let _ = writeln!(sql, "-- removal is operational, not migration-driven.");
    }

    // Roadmap §1.5 (CL.C.2) — emit commented `DROP INDEX` for each
    // `@full_text` GIN index. DDL drop is implicit via DROP TABLE; the
    // commented hints exist for operators dropping indexes ahead of a
    // clean reload.
    if !full_text_fields.is_empty() {
        let _ = writeln!(sql);
        for field in full_text_fields {
            let _ = writeln!(
                sql,
                "-- DROP INDEX {};",
                sql_ident(&format!("{}_{}_fts", table_name, field.name))
            );
        }
    }

    let authored_indexes: Vec<String> = resource
        .constraints
        .iter()
        .filter_map(|constraint| {
            let Constraint::Index(index) = constraint else {
                return None;
            };
            authored_index_name(&table_name, index)
        })
        .collect();
    if !authored_indexes.is_empty() {
        let _ = writeln!(sql);
        for name in authored_indexes {
            let _ = writeln!(sql, "-- DROP INDEX {};", sql_ident(&name));
        }
    }

    sql
}

pub(super) fn emit_audit_log_down_migration() -> GeneratedFile {
    GeneratedFile {
        path: "migrations/audit_log.down.sql".to_owned(),
        contents: "\
-- Code generated by lazuli; DO NOT EDIT.
-- rollback for audit_log

DROP TABLE IF EXISTS audit_log;
"
        .to_owned(),
    }
}

fn variant(name: &str, value: Option<StorageValue>) -> EnumVariant {
    EnumVariant {
        name: name.to_owned(),
        storage_value: value,
        label_key: None,
        hint_key: None,
        icon_key: None,
        previous_names: Vec::new(),
    }
}

fn make_enum(name: &str, variants: Vec<EnumVariant>) -> EnumDecl {
    EnumDecl {
        name: name.to_owned(),
        public_contract: None,
        variants,
        previous_names: Vec::new(),
        span_ref: None,
    }
}


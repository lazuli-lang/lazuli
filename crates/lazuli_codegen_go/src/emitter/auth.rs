    #[test]
    fn feature_without_auth_returns_none() {
        let feature = base_feature("customer");
        assert!(emit(&feature).is_none());
    }

    #[test]
    fn full_auth_block_emits_runtime_contracts() {
        let mut feature = base_feature("customer_auth");
        let mut auth = auth_with_identity("Customer", "email");
        auth.password = Some(AuthPassword {
            algorithm: "argon2id".to_owned(),
            hash: "@fn.hash_customer_password".to_owned(),
            verify: "@fn.verify_customer_password".to_owned(),
            rate_limit: Some("5 per 10 minutes".to_owned()),
        });
        auth.sessions = Some(AuthSessions {
            resource: qname("CustomerSession"),
            ttl: "7 days".to_owned(),
            refresh: false,
        });
        auth.mfa = Some(AuthMfa {
            method: "totp".to_owned(),
            enroll: "@fn.enroll_customer_totp".to_owned(),
            verify: "@validator.verify_customer_totp".to_owned(),
            adapter: None,
        });
        auth.oauth.push(AuthOAuthProvider {
            provider: "google".to_owned(),
            adapter: "@adapter.google_oauth".to_owned(),
        });
        feature.auth = Some(auth);

        let out = emit(&feature).expect("must emit");
        assert!(out.contains("package customer_auth"));
        assert!(out.contains("\"time\""));
        assert!(out.contains("\"lazuli.dev/runtime/lazuli/auth\""));
        assert!(out.contains(
            "var customerAuthAuthIdentity = auth.FieldRef{Resource: \"Customer\", Field: \"email\"}"
        ));
        assert!(out.contains("var customerAuthAuthPassword = auth.PasswordContract{"));
        assert!(out.contains("Identity:  customerAuthAuthIdentity,"));
        assert!(out.contains("Algorithm: auth.AlgoArgon2id,"));
        assert!(out.contains("HashFn:    \"@fn.hash_customer_password\","));
        assert!(out.contains("RateLimit: \"5 per 10 minutes\","));
        assert!(out.contains("var customerAuthAuthSessions = auth.SessionsContract{"));
        assert!(out.contains("TTL:      7 * 24 * time.Hour,"));
        assert!(out.contains("Refresh:  false,"));
        assert!(out.contains("var customerAuthAuthOAuthGoogle = auth.OAuthContract{"));
        assert!(out.contains("AdapterRef: \"@adapter.google_oauth\","));
        assert!(out.contains("var customerAuthAuthMfa = auth.MfaContract{"));
        assert!(out.contains("Method:   auth.MfaMethodTOTP,"));
    }

    #[test]
    fn identity_only_auth_skips_optional_contracts() {
        let mut feature = base_feature("portal");
        feature.auth = Some(auth_with_identity("User", "email"));
        let out = emit(&feature).expect("must emit");
        assert!(out.contains("var portalAuthIdentity = auth.FieldRef"));
        assert!(!out.contains("PasswordContract"));
        assert!(!out.contains("SessionsContract"));
        assert!(!out.contains("MfaContract"));
        assert!(!out.contains("OAuthContract"));
        assert!(!out.contains("\"time\""));
    }

    #[test]
    fn oauth_providers_are_sorted_for_determinism() {
        let mut feature = base_feature("customer");
        let mut auth = auth_with_identity("Customer", "email");
        auth.oauth.push(AuthOAuthProvider {
            provider: "microsoft".to_owned(),
            adapter: "@adapter.microsoft_oauth".to_owned(),
        });
        auth.oauth.push(AuthOAuthProvider {
            provider: "google".to_owned(),
            adapter: "@adapter.google_oauth".to_owned(),
        });
        feature.auth = Some(auth);

        let a = emit(&feature).expect("must emit");
        let b = emit(&feature).expect("must emit");
        assert_eq!(a, b);
        let google_pos = a.find("AuthOAuthGoogle").expect("google contract");
        let microsoft_pos = a.find("AuthOAuthMicrosoft").expect("microsoft contract");
        assert!(google_pos < microsoft_pos);
    }

    #[test]
    fn non_catalog_values_still_emit_go_valid_conversions() {
        let mut feature = base_feature("customer");
        let mut auth = auth_with_identity("Customer", "email");
        auth.password = Some(AuthPassword {
            algorithm: "scrypt".to_owned(),
            hash: "@fn.hash".to_owned(),
            verify: "@fn.verify".to_owned(),
            rate_limit: None,
        });
        auth.mfa = Some(AuthMfa {
            method: "sms".to_owned(),
            enroll: "@fn.enroll_sms".to_owned(),
            verify: "@fn.verify_sms".to_owned(),
            adapter: Some("@adapter.sms".to_owned()),
        });
        auth.sessions = Some(AuthSessions {
            resource: qname("CustomerSession"),
            ttl: "soon".to_owned(),
            refresh: true,
        });
        feature.auth = Some(auth);

        let out = emit(&feature).expect("must emit");
        assert!(out.contains("Algorithm: auth.PasswordAlgorithm(\"scrypt\"),"));
        assert!(out.contains("Method:     auth.MfaMethod(\"sms\"),"));
        assert!(out.contains("AdapterRef: \"@adapter.sms\","));
        assert!(out.contains("TTL:      0 * time.Second,"));
        assert!(out.contains("// TODO(auth-ttl): unsupported AuthSessions.ttl literal \"soon\""));
    }

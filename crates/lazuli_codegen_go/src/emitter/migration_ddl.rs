//! DDL migration emission for resource tables. This walker is kept
//! standalone so the top-level orchestrator can wire it into
//! `generate_v1` after merge without changing the resource/codegen
//! emitters in this branch.

use std::fmt::Write;

use lazuli_ir::{
    AuthSessions, BuiltinType, CapabilityRef, CompositeKey, Constraint, Feature, Field, Module,
    Resource, Tenancy, TypeRef,
};

use super::cross_feature::CrossFeatureIndex;
use crate::GeneratedFile;

/// Emit SQL migrations in deterministic, cross-feature lexical order.
///
/// The returned paths are relative to the generated Go output root:
/// `migrations/<NNN>_<feature>_<resource>.sql` plus companion
/// `migrations/<NNN>_<feature>_<resource>.down.sql` rollback files.
/// The shared audit table rollback is emitted here because the matching
/// `migrations/audit_log.sql` up migration is always emitted by the
/// top-level module emitter.
pub fn emit_migrations(module: &Module, source_label: &str) -> Vec<GeneratedFile> {
    let cross_index = CrossFeatureIndex::build(module);
    let raw_resources: Vec<(&Feature, &Resource)> = module
        .features
        .iter()
        .flat_map(|feature| {
            feature
                .resources
                .iter()
                .map(move |resource| (feature, resource))
        })
        .collect();

    // WAR-RUNTIME-MIGRATION-03 — order resources so every FK target's
    // CREATE TABLE runs BEFORE the referencing FOREIGN KEY constraint.
    // Lexical (feature, resource) is the tiebreaker for resources with
    // no dependency between them, so output stays stable when the
    // dependency graph doesn't pin a relative order.
    let resources = topo_sort_resources(module, &raw_resources, &cross_index);

    let mut files = Vec::with_capacity(resources.len() * 2 + 1);

    for (idx, (feature, resource)) in resources.iter().copied().enumerate() {
        let resource_slug = lower_snake(&resource.name);
        files.push(GeneratedFile {
            path: format!(
                "migrations/{:03}_{}_{}.sql",
                idx + 1,
                feature.name,
                resource_slug
            ),
            contents: emit_resource_migration(
                module,
                feature,
                resource,
                source_label,
                &cross_index,
            ),
        });
    }

    for (idx, (feature, resource)) in resources.iter().copied().enumerate() {
        let resource_slug = lower_snake(&resource.name);
        files.push(GeneratedFile {
            path: format!(
                "migrations/{:03}_{}_{}.down.sql",
                idx + 1,
                feature.name,
                resource_slug
            ),
            contents: emit_resource_down_migration(feature, resource),
        });
    }

    files.push(emit_audit_log_down_migration());
    files
}

fn emit_resource_migration<'a>(
    module: &'a Module,
    feature: &'a Feature,
    resource: &'a Resource,
    source_label: &str,
    cross_index: &CrossFeatureIndex<'a>,
) -> String {
    let table_name = lower_snake(&resource.name);
    let geo_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| is_direct_geo_point(&field.type_ref))
        .collect();
    // Roadmap §1.5 (CL.C.2) — fields decorated with `@full_text` get a
    // GIN index over `to_tsvector('english', <field>)` so the runtime
    // can execute `@@ websearch_to_tsquery(...)` queries against them.
    let full_text_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| field.full_text)
        .collect();

    let mut sql = String::new();
    writeln!(sql, "-- Code generated by lazuli; DO NOT EDIT.").unwrap();
    writeln!(sql, "-- source: {}", comment_value(source_label)).unwrap();
    writeln!(
        sql,
        "-- resource: {}.{}",
        comment_value(&feature.name),
        comment_value(&resource.name)
    )
    .unwrap();
    writeln!(sql).unwrap();

    if resource_uses_postgis(resource) {
        writeln!(sql, "CREATE EXTENSION IF NOT EXISTS postgis;").unwrap();
        writeln!(sql).unwrap();
    }

    writeln!(
        sql,
        "CREATE TABLE IF NOT EXISTS {} (",
        quote_ident(&table_name)
    )
    .unwrap();

    let columns = resource_columns(module, feature, resource, cross_index);
    for (idx, column) in columns.iter().enumerate() {
        let comma = if idx + 1 == columns.len() { "" } else { "," };
        // Trailing-comment columns place the comma *before* the
        // comment so the SQL stays valid (`<body>, -- <comment>`
        // instead of `<body> -- <comment>,`).
        if let Some(comment) = column.trailing_comment() {
            writeln!(
                sql,
                "    {body}{comma} -- {comment}",
                body = column.render_body(),
            )
            .unwrap();
        } else {
            writeln!(sql, "    {}{}", column.render_body(), comma).unwrap();
        }
    }
    writeln!(sql, ");").unwrap();

    for field in geo_fields {
        writeln!(sql).unwrap();
        writeln!(
            sql,
            "CREATE INDEX {} ON {} USING GIST ({});",
            sql_ident(&format!("{}_{}_gist", table_name, field.name)),
            quote_ident(&table_name),
            sql_ident(&field.name)
        )
        .unwrap();
    }

    // Roadmap §1.5 (CL.C.2) — `@full_text` fields → GIN tsvector index.
    for field in full_text_fields {
        writeln!(sql).unwrap();
        writeln!(
            sql,
            "CREATE INDEX {} ON {} USING GIN (to_tsvector('english', {}));",
            sql_ident(&format!("{}_{}_fts", table_name, field.name)),
            quote_ident(&table_name),
            sql_ident(&field.name)
        )
        .unwrap();
    }

    if session_rotation_enabled_for_resource(module, feature, resource).is_some() {
        emit_session_rotation_indexes(&mut sql, &table_name);
    }

    sql
}

fn emit_resource_down_migration(feature: &Feature, resource: &Resource) -> String {
    let table_name = lower_snake(&resource.name);
    let geo_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| is_direct_geo_point(&field.type_ref))
        .collect();
    let full_text_fields: Vec<&Field> = resource
        .fields
        .iter()
        .filter(|field| field.full_text)
        .collect();

    let mut sql = String::new();
    writeln!(sql, "-- Code generated by lazuli; DO NOT EDIT.").unwrap();
    writeln!(
        sql,
        "-- rollback for {}.{}",
        comment_value(&feature.name),
        comment_value(&resource.name)
    )
    .unwrap();
    writeln!(sql).unwrap();
    writeln!(sql, "DROP TABLE IF EXISTS {};", quote_ident(&table_name)).unwrap();
    writeln!(
        sql,
        "-- Note: cross-feature FK columns rely on parent feature's down migration"
    )
    .unwrap();
    writeln!(
        sql,
        "-- to drop their target. Run rollbacks in reverse order if cascading."
    )
    .unwrap();

    if !geo_fields.is_empty() {
        writeln!(sql).unwrap();
        for field in geo_fields {
            writeln!(
                sql,
                "-- DROP INDEX {};",
                sql_ident(&format!("{}_{}_gist", table_name, field.name))
            )
            .unwrap();
        }
        writeln!(
            sql,
            "-- Note: `CREATE EXTENSION postgis` is NOT dropped here \u{2014} extension"
        )
        .unwrap();
        writeln!(sql, "-- removal is operational, not migration-driven.").unwrap();
    }

    // Roadmap §1.5 (CL.C.2) — emit commented `DROP INDEX` for each
    // `@full_text` GIN index. DDL drop is implicit via DROP TABLE; the
    // commented hints exist for operators dropping indexes ahead of a
    // clean reload.
    if !full_text_fields.is_empty() {
        writeln!(sql).unwrap();
        for field in full_text_fields {
            writeln!(
                sql,
                "-- DROP INDEX {};",
                sql_ident(&format!("{}_{}_fts", table_name, field.name))
            )
            .unwrap();
        }
    }

    sql
}

fn emit_audit_log_down_migration() -> GeneratedFile {
    GeneratedFile {
        path: "migrations/audit_log.down.sql".to_owned(),
        contents: "\
-- Code generated by lazuli; DO NOT EDIT.
-- rollback for audit_log

DROP TABLE IF EXISTS audit_log;
"
        .to_owned(),
    }
}

fn resource_columns<'a>(
    module: &'a Module,
    feature: &'a Feature,
    resource: &'a Resource,
    cross_index: &CrossFeatureIndex<'a>,
) -> Vec<SqlColumn> {
    let mut columns = Vec::new();

    // Roadmap §1.5 (CL.C.2) — `composite_key primary true` replaces the
    // implicit `id BIGSERIAL PRIMARY KEY` with a `PRIMARY KEY (<fields>)`
    // tail clause. When `primary` is `false` (or `composite_key` is
    // absent), the implicit row identity is kept and the composite is
    // emitted as a `UNIQUE` constraint via `composite_key_sql` below.
    let composite_primary = matches!(
        &resource.composite_key,
        Some(CompositeKey { primary: true, .. })
    );
    if !composite_primary {
        columns.push(SqlColumn::raw("id BIGSERIAL PRIMARY KEY"));
    }

    let tenancy = effective_tenancy(feature, resource);
    if matches!(tenancy, Tenancy::Org) {
        columns.push(SqlColumn::typed("org_id", "BIGINT", true));
    }

    // MONEY-1 §3.2 (v0.5) — every `Money` field carries its currency
    // through to IR (`BuiltinType::SemanticMoney { currency }`). DDL
    // emits a paired `<field>_currency TEXT NOT NULL CHECK (<field>
    // _currency = '<ISO>') DEFAULT '<ISO>'` immediately after the
    // amount column. The v0.4 single-shared `currency TEXT` column
    // pattern is retired — IR is now precise enough that the per-field
    // shape is unambiguous and the CHECK constraint defends against
    // ALTER-time drift. Authors keep the option to suppress the
    // auto-emitted paired column by declaring `<field>_currency:
    // Currency` themselves — useful when migrating an existing schema
    // that already has the legacy column shape.
    let explicit_currency_overrides: std::collections::HashSet<String> = resource
        .fields
        .iter()
        .filter_map(|f| {
            if matches!(
                f.type_ref,
                lazuli_ir::TypeRef::Builtin(lazuli_ir::BuiltinType::SemanticCurrency)
            ) {
                f.name
                    .strip_suffix("_currency")
                    .map(|stem| stem.to_owned())
            } else {
                None
            }
        })
        .collect();

    for field in &resource.fields {
        let pg_type = pg_type_for_field(module, feature, field, cross_index);
        let column = SqlColumn::typed_generated(
            &field.name,
            &pg_type.sql,
            field.required,
            field.derived_from.clone(),
        );
        let column = match encryption_marker_for(field) {
            Some(marker) => column.with_trailing_comment(marker),
            None => column,
        };
        columns.push(column);
        if let lazuli_ir::TypeRef::Builtin(lazuli_ir::BuiltinType::SemanticMoney {
            currency,
        }) = field.type_ref
        {
            if explicit_currency_overrides.contains(&field.name) {
                // Paired column was authored explicitly — defer to the
                // user's declaration.
                continue;
            }
            let iso = currency.as_iso();
            let name = format!("{}_currency", field.name);
            // `field.required` mirrors the amount column's nullability.
            // Defaults to the declared ISO so old inserts (or hand-
            // written ALTER backfills) cannot break the invariant.
            columns.push(SqlColumn::raw(&format!(
                "{} TEXT{} CHECK ({} = '{}') DEFAULT '{}'",
                name,
                if field.required { " NOT NULL" } else { "" },
                name,
                iso,
                iso,
            )));
        }
    }

    if session_rotation_enabled_for_resource(module, feature, resource).is_some() {
        extend_session_rotation_columns(&mut columns, resource, &lower_snake(&resource.name));
    }

    if uses_timestamps(feature, resource) {
        columns.push(SqlColumn::raw(
            "created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()",
        ));
        columns.push(SqlColumn::raw(
            "updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()",
        ));
    }

    if resource.soft_delete {
        columns.push(SqlColumn::typed("deleted_at", "TIMESTAMPTZ", false));
    }

    columns.extend(inline_unique_constraint_sql(resource, &tenancy));
    columns.extend(
        resource
            .constraints
            .iter()
            .filter_map(unique_constraint_sql),
    );
    if let Some(ck_sql) = composite_key_sql(resource) {
        columns.push(ck_sql);
    }
    columns.extend(foreign_key_constraints(
        module,
        feature,
        resource,
        cross_index,
    ));

    columns
}

fn session_rotation_enabled_for_resource<'a>(
    module: &'a Module,
    resource_feature: &Feature,
    resource: &Resource,
) -> Option<&'a AuthSessions> {
    module.features.iter().find_map(|auth_feature| {
        let sessions = auth_feature.auth.as_ref()?.sessions.as_ref()?;
        if sessions.is_rotation_enabled()
            && session_resource_matches(auth_feature, sessions, resource_feature, resource)
        {
            Some(sessions)
        } else {
            None
        }
    })
}

fn session_resource_matches(
    auth_feature: &Feature,
    sessions: &AuthSessions,
    resource_feature: &Feature,
    resource: &Resource,
) -> bool {
    if sessions.resource.name != resource.name {
        return false;
    }

    match sessions.resource.feature.as_deref() {
        Some(owner) => owner == resource_feature.name,
        None => auth_feature.name == resource_feature.name,
    }
}

fn extend_session_rotation_columns(columns: &mut Vec<SqlColumn>, resource: &Resource, table: &str) {
    push_if_missing(
        columns,
        resource,
        "refresh_token_hash",
        "refresh_token_hash TEXT NOT NULL DEFAULT ''",
    );
    push_if_missing(
        columns,
        resource,
        "refresh_expires_at",
        "refresh_expires_at TIMESTAMPTZ",
    );
    push_if_missing(
        columns,
        resource,
        "parent_session_id",
        &format!(
            "parent_session_id BIGINT REFERENCES {} (id) ON DELETE SET NULL",
            quote_ident(table)
        ),
    );
    push_if_missing(
        columns,
        resource,
        "theft_detected_at",
        "theft_detected_at TIMESTAMPTZ",
    );
}

fn push_if_missing(columns: &mut Vec<SqlColumn>, resource: &Resource, name: &str, ddl: &str) {
    if !resource.fields.iter().any(|field| field.name == name) {
        columns.push(SqlColumn::raw(ddl));
    }
}

fn emit_session_rotation_indexes(sql: &mut String, table: &str) {
    writeln!(sql).unwrap();
    writeln!(
        sql,
        "CREATE INDEX ON {} (parent_session_id) WHERE parent_session_id IS NOT NULL;",
        quote_ident(table)
    )
    .unwrap();
    writeln!(sql).unwrap();
    writeln!(
        sql,
        "CREATE INDEX ON {} (refresh_token_hash) WHERE refresh_token_hash != '';",
        quote_ident(table)
    )
    .unwrap();
}

/// Roadmap §1.5 (CL.C.2) — render the `composite_key` block as either a
/// `PRIMARY KEY (<fields>)` clause (when `primary true`) or a
/// `UNIQUE (<fields>)` constraint (when `primary false`). The
/// `Resource.lock` + `Resource.composite_key` axes are independent;
/// this helper only knows about composite key emission.
fn composite_key_sql(resource: &Resource) -> Option<SqlColumn> {
    let ck = resource.composite_key.as_ref()?;
    if ck.fields.is_empty() {
        return None;
    }
    let cols: Vec<String> = ck.fields.iter().map(|f| sql_ident(f)).collect();
    let clause = if ck.primary {
        format!("PRIMARY KEY ({})", cols.join(", "))
    } else {
        format!("UNIQUE ({})", cols.join(", "))
    };
    Some(SqlColumn::raw(&clause))
}

enum SqlColumn {
    Raw(String),
    Typed {
        name: String,
        pg_type: String,
        required: bool,
        generated_as: Option<String>,
        /// Trailing SQL comment for operator visibility (e.g.
        /// `lazuli:encrypted @key.tenant`). Rendered as a `-- ...`
        /// suffix on the column line; no semantic effect on the DDL.
        trailing_comment: Option<String>,
    },
}

impl SqlColumn {
    fn raw(sql: &str) -> Self {
        Self::Raw(sql.to_owned())
    }

    fn typed(name: &str, pg_type: &str, required: bool) -> Self {
        Self::Typed {
            name: name.to_owned(),
            pg_type: pg_type.to_owned(),
            required,
            generated_as: None,
            trailing_comment: None,
        }
    }

    fn typed_generated(
        name: &str,
        pg_type: &str,
        required: bool,
        generated_as: Option<String>,
    ) -> Self {
        Self::Typed {
            name: name.to_owned(),
            pg_type: pg_type.to_owned(),
            required,
            generated_as,
            trailing_comment: None,
        }
    }

    fn with_trailing_comment(mut self, comment: String) -> Self {
        if let Self::Typed {
            trailing_comment, ..
        } = &mut self
        {
            *trailing_comment = Some(comment);
        }
        self
    }

    /// Body of the column line, without any trailing comment. The
    /// emitter appends the comma + comment separately so we don't
    /// end up with `BYTEA -- lazuli:encrypted, NOT NULL` (the comma
    /// belongs after the type and before the comment, not after the
    /// comment).
    fn render_body(&self) -> String {
        match self {
            Self::Raw(sql) => sql.clone(),
            Self::Typed {
                name,
                pg_type,
                required,
                generated_as,
                ..
            } => {
                let mut rendered = format!("{} {}", sql_ident(name), pg_type);
                if *required {
                    rendered.push_str(" NOT NULL");
                }
                if let Some(expr) = generated_as {
                    rendered.push_str(" GENERATED ALWAYS AS (");
                    rendered.push_str(expr);
                    rendered.push_str(") STORED");
                }
                rendered
            }
        }
    }

    fn trailing_comment(&self) -> Option<&str> {
        if let Self::Typed {
            trailing_comment, ..
        } = self
        {
            trailing_comment.as_deref()
        } else {
            None
        }
    }

    /// Back-compat: callers that only need the body (down-migration,
    /// audit DDL) continue to call `render`. Equivalent to
    /// `render_body` plus an inline `-- comment` suffix when
    /// declared, but the caller is responsible for placing the comma
    /// — see `emit_resource_migration` for the up-migration loop that
    /// preserves comma-before-comment ordering.
    fn render(&self) -> String {
        let body = self.render_body();
        match self.trailing_comment() {
            Some(comment) => format!("{body} -- {comment}"),
            None => body,
        }
    }
}

struct PgType {
    sql: String,
    uses_postgis: bool,
}

fn pg_type_for(type_ref: &TypeRef) -> PgType {
    match type_ref {
        TypeRef::Builtin(builtin) => pg_type_for_builtin(builtin),
        TypeRef::Many(inner) => {
            let inner = pg_type_for(inner);
            PgType {
                sql: format!("{}[]", inner.sql),
                uses_postgis: inner.uses_postgis,
            }
        }
        TypeRef::Capability(capability) => pg_type_for_capability(capability),
        TypeRef::UserDefined(_) | TypeRef::EnumRef(_) | TypeRef::Unresolved(_) => PgType {
            sql: "TEXT".to_owned(),
            uses_postgis: false,
        },
    }
}

fn pg_type_for_field<'a>(
    module: &'a Module,
    feature: &'a Feature,
    field: &'a Field,
    cross_index: &CrossFeatureIndex<'a>,
) -> PgType {
    if let TypeRef::UserDefined(qname) = &field.type_ref {
        if foreign_key_owner(module, feature, qname, cross_index).is_some() {
            return PgType {
                sql: "BIGINT".to_owned(),
                uses_postgis: false,
            };
        }
    }

    pg_type_for(&field.type_ref)
}

fn pg_type_for_builtin(builtin: &BuiltinType) -> PgType {
    let sql = match builtin {
        BuiltinType::Id => "BIGINT",
        BuiltinType::Text => "TEXT",
        BuiltinType::Boolean => "BOOLEAN",
        BuiltinType::Integer => "BIGINT",
        BuiltinType::Decimal => "NUMERIC(20, 6)",
        BuiltinType::Date => "DATE",
        BuiltinType::DateTime => "TIMESTAMPTZ",
        BuiltinType::Json => "JSONB",
        BuiltinType::SemanticEmail
        | BuiltinType::SemanticPhone
        | BuiltinType::SemanticUrl
        | BuiltinType::SemanticUuid
        | BuiltinType::SemanticCurrency => "TEXT",
        // Per proposal `semantic-types-money-brazilian.md` v0.4:
        // Money stores as `NUMERIC(20,4)`. One shared resource-level
        // `currency TEXT` column is auto-emitted (see resource_columns);
        // authors opt out per-field by declaring an explicit
        // `<money>_currency: Currency` pair.
        BuiltinType::SemanticMoney { .. } => "NUMERIC(20,4)",
        BuiltinType::SemanticGeoPoint => {
            return PgType {
                sql: "geography(point, 4326)".to_owned(),
                uses_postgis: true,
            };
        }
        // B3 — plugin-contributed `@semantic.<Name>` columns inherit
        // the DDL of the carrier. v1 closed-catalog carrier is `String`
        // → `TEXT` (per `docs/proposals/semantic-types-plugin-locales.md`
        // §Manifest mechanism — non-string carriers need a separate
        // proposal because they affect DDL + wire shape).
        BuiltinType::SemanticPluginType { carrier, .. } => return pg_type_for_builtin(carrier),
        BuiltinType::CapSecret => "TEXT",
        BuiltinType::CapFile => "JSONB",
    };

    PgType {
        sql: sql.to_owned(),
        uses_postgis: false,
    }
}

fn pg_type_for_capability(capability: &CapabilityRef) -> PgType {
    // `@cap.Encrypted` / `@cap.E2ee` columns store the AES-256-GCM
    // ciphertext envelope (`nonce || ciphertext || tag`) — BYTEA. The
    // `EncryptCustomer`/`DecryptCustomer` helpers in `resource.gen.go`
    // thread these bytes through `encryption.ForCtx` at the SQL
    // boundary. `@cap.File(...)` columns store the JSONB FileRef
    // shape `{key, content_type, size}` populated by the storage
    // runtime's `confirm_*_upload` lowering — see
    // docs/proposals/fileref-jsonb-roundtrip.md. Hashed + Token
    // capabilities stay TEXT until a pilot demands a richer shape.
    let sql = match capability {
        CapabilityRef::Encrypted(_) | CapabilityRef::E2ee(_) => "BYTEA",
        CapabilityRef::File(_) => "JSONB",
        _ => "TEXT",
    };
    PgType {
        sql: sql.to_owned(),
        uses_postgis: false,
    }
}

/// Render the operator-visibility marker for an `@cap.Encrypted` /
/// `@cap.E2ee` column. Lifted into the SQL as a trailing `-- ...`
/// comment so DBAs cold-reading the schema see which `@key.<scope>`
/// each encrypted column resolves through.
fn encryption_marker_for(field: &Field) -> Option<String> {
    match &field.type_ref {
        TypeRef::Capability(CapabilityRef::Encrypted(cap)) => {
            Some(format!("lazuli:encrypted {} algorithm=aes_256_gcm", cap.key))
        }
        TypeRef::Capability(CapabilityRef::E2ee(cap)) => {
            Some(format!("lazuli:e2ee {} algorithm=aes_256_gcm", cap.key))
        }
        _ => None,
    }
}

fn unique_constraint_sql(constraint: &Constraint) -> Option<SqlColumn> {
    let Constraint::Unique(unique) = constraint else {
        return None;
    };

    unique_fields_sql(
        unique.fields.iter().map(String::as_str),
        unique.per.as_deref(),
    )
}

fn inline_unique_constraint_sql(resource: &Resource, tenancy: &Tenancy) -> Vec<SqlColumn> {
    let per = if matches!(tenancy, Tenancy::Org) {
        Some("Org")
    } else {
        None
    };
    resource
        .fields
        .iter()
        .filter(|field| field.unique)
        .filter_map(|field| unique_fields_sql(std::iter::once(field.name.as_str()), per))
        .collect()
}

fn unique_fields_sql<'a>(
    fields: impl IntoIterator<Item = &'a str>,
    per: Option<&str>,
) -> Option<SqlColumn> {
    let mut fields: Vec<String> = fields.into_iter().map(sql_ident).collect();
    if fields.is_empty() {
        return None;
    }
    if let Some(per) = per {
        fields.push(sql_ident(&format!("{}_id", lower_snake(per))));
    }
    Some(SqlColumn::raw(&format!("UNIQUE ({})", fields.join(", "))))
}

/// Kahn-style topo sort over (feature, resource) pairs. Edges run from
/// referencing resource → FK target resource (target must come first).
/// Ties break by lexical (feature, resource) order so output is stable
/// for unrelated subgraphs. Cycles fall back to lexical order with a
/// warning on stderr — a cycle in FK direction is a data-model bug the
/// doctor should catch separately; codegen degrades gracefully so the
/// emit still produces consumable migrations.
fn topo_sort_resources<'a>(
    module: &'a Module,
    resources: &[(&'a Feature, &'a Resource)],
    cross_index: &CrossFeatureIndex<'a>,
) -> Vec<(&'a Feature, &'a Resource)> {
    use std::collections::{BTreeMap, BTreeSet, VecDeque};

    type Key = (String, String);

    let key = |f: &Feature, r: &Resource| -> Key { (f.name.clone(), r.name.clone()) };

    // Build lookup table from (feature, resource) → index into the input
    // slice. Lexical key ordering is what BTreeMap provides natively, so
    // we lean on it for the tiebreaker.
    let mut by_key: BTreeMap<Key, usize> = BTreeMap::new();
    for (idx, (feature, resource)) in resources.iter().enumerate() {
        by_key.insert(key(feature, resource), idx);
    }

    // Adjacency: target_key → set of dependents. In-degree counts how
    // many FK targets a resource still depends on.
    let mut dependents: BTreeMap<Key, BTreeSet<Key>> = BTreeMap::new();
    let mut in_degree: BTreeMap<Key, usize> = BTreeMap::new();
    for (feature, resource) in resources {
        in_degree.insert(key(feature, resource), 0);
    }

    for (feature, resource) in resources {
        let dependent_key = key(feature, resource);
        for field in &resource.fields {
            let TypeRef::UserDefined(qname) = &field.type_ref else {
                continue;
            };
            // Resolve target feature exactly the way `foreign_key_owner`
            // does — same-feature and cross-feature both produce a FK.
            let owner = match qname.feature.as_deref() {
                Some(owner) => Some(owner.to_owned()),
                None => cross_index.owner(&qname.name).map(str::to_owned),
            };
            let Some(owner) = owner else { continue };
            if !feature_declares_resource(module, &owner, &qname.name) {
                continue;
            }
            let target_key = (owner, qname.name.clone());
            // Skip self-references — they don't change topo order and
            // would otherwise show as a 1-node cycle.
            if target_key == dependent_key {
                continue;
            }
            let inserted = dependents
                .entry(target_key)
                .or_default()
                .insert(dependent_key.clone());
            if inserted {
                *in_degree.entry(dependent_key.clone()).or_insert(0) += 1;
            }
        }
    }

    // Kahn's algorithm: ready queue holds zero-in-degree nodes sorted
    // lexically. Pop the smallest, emit it, decrement in-degree of its
    // dependents, requeue any that hit zero.
    let mut ready: BTreeSet<Key> = in_degree
        .iter()
        .filter_map(|(k, &deg)| (deg == 0).then(|| k.clone()))
        .collect();

    let mut ordered: Vec<(&'a Feature, &'a Resource)> = Vec::with_capacity(resources.len());
    let mut emitted: BTreeSet<Key> = BTreeSet::new();

    while let Some(next_key) = ready.iter().next().cloned() {
        ready.remove(&next_key);
        if let Some(&idx) = by_key.get(&next_key) {
            ordered.push(resources[idx]);
            emitted.insert(next_key.clone());
        }
        if let Some(deps) = dependents.get(&next_key) {
            for dependent in deps {
                if let Some(deg) = in_degree.get_mut(dependent) {
                    if *deg > 0 {
                        *deg -= 1;
                        if *deg == 0 {
                            ready.insert(dependent.clone());
                        }
                    }
                }
            }
        }
    }

    if ordered.len() != resources.len() {
        // Cycle detected — append the remainder in lexical order so the
        // emit completes. Doctor should flag the cycle separately; codegen
        // refuses to silently drop tables.
        eprintln!(
            "warning: migration FK topo sort detected a cycle ({} of {} resources unresolved); falling back to lexical for the remainder",
            resources.len() - ordered.len(),
            resources.len()
        );
        let mut remainder: Vec<&Key> = in_degree
            .keys()
            .filter(|k| !emitted.contains(*k))
            .collect();
        remainder.sort();
        for k in remainder {
            if let Some(&idx) = by_key.get(k) {
                ordered.push(resources[idx]);
            }
        }
    }

    let mut deque: VecDeque<(&'a Feature, &'a Resource)> = VecDeque::from(ordered);
    let mut out: Vec<(&'a Feature, &'a Resource)> = Vec::with_capacity(deque.len());
    while let Some(item) = deque.pop_front() {
        out.push(item);
    }
    out
}

fn foreign_key_constraints<'a>(
    module: &'a Module,
    feature: &'a Feature,
    resource: &'a Resource,
    cross_index: &CrossFeatureIndex<'a>,
) -> Vec<SqlColumn> {
    resource
        .fields
        .iter()
        .filter_map(|field| {
            let TypeRef::UserDefined(qname) = &field.type_ref else {
                return None;
            };
            // `foreign_key_owner` returns `Some` only when the target
            // resource is declared in a different feature of the same
            // module — used here purely to confirm the FK target's
            // migration will exist before we point at it.
            let _owner = foreign_key_owner(module, feature, qname, cross_index)?;
            // FK target = the bare table name emitted by
            // `emit_resource_migration` (line 88) and stored on
            // `lazuli.Resource[T].Name` (consumed by the Go runtime in
            // `handle.go` `INSERT INTO eff.Resource.Name`). The
            // previous `<feature>_<resource>` form drifted from those
            // call sites and produced FKs pointing to non-existent
            // tables — migrations would refuse to apply.
            let target_table = lower_snake(&qname.name);
            Some(SqlColumn::raw(&format!(
                "FOREIGN KEY ({}) REFERENCES {} (id)",
                sql_ident(&field.name),
                quote_ident(&target_table)
            )))
        })
        .collect()
}

fn foreign_key_owner<'a>(
    module: &'a Module,
    feature: &'a Feature,
    qname: &'a lazuli_ir::QualifiedName,
    cross_index: &CrossFeatureIndex<'a>,
) -> Option<&'a str> {
    // Resolve the owning feature regardless of whether the reference is
    // cross-feature or same-feature. The previous filter dropped
    // same-feature refs entirely, which silently lost referential
    // integrity for in-feature relations (e.g. a `Category.parent:
    // Category` parent-child link emitted no FK constraint at all).
    //
    // Discovered while writing the cross-feature regression test for
    // bug #9 (2026-05-15) — `Membership.workspace: Workspace` in the
    // same feature as `Workspace` produced no FK while the cross-feature
    // `Membership.user: User` did. Now both paths emit an FK pointing at
    // the matching `CREATE TABLE`.
    let owner = match qname.feature.as_deref() {
        Some(owner) => Some(owner),
        None => cross_index.owner(&qname.name),
    }?;

    feature_declares_resource(module, owner, &qname.name).then_some(owner)
}

fn feature_declares_resource(module: &Module, feature_name: &str, resource_name: &str) -> bool {
    module.features.iter().any(|feature| {
        feature.name == feature_name
            && feature
                .resources
                .iter()
                .any(|resource| resource.name == resource_name)
    })
}


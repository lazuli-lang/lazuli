//! Framework-synthesized table DDL emission (W2-4).
//!
//! The Lazuli Go runtime hard-wires SQL against a handful of
//! framework-synthesized tables that are NOT authored resources. Their
//! `CREATE TABLE` migrations must ship in every pilot whose IR activates the
//! corresponding runtime path, or the app 500s at runtime
//! (`relation "<table>" does not exist`).
//!
//! `audit_log` has always been emitted unconditionally by
//! [`super::audit::emit_audit_log_ddl`]. This module GENERALIZES that
//! point-fix to the rest of the synthesized-table set, gating each on the
//! activating IR construct so a pilot that never audits / never uses a
//! guaranteed outbox does not accrue dead tables:
//!
//! - `lazuli_audit`  — emitted when any command declares `audit ...`
//!   (`handle.go::writeAuditRow`, SEC-C2).
//! - `lazuli_outbox` — emitted when any event opts into `outbox guaranteed`
//!   (`handle.go::writeGuaranteedOutboxRows`, EVENT-OUTBOX §3.3 producer).
//! - `lazuli_inbox`  — emitted alongside the outbox (the receiver-side
//!   idempotency table the same EVENT-OUTBOX §3.3 machinery consumes).
//!
//! The static SQL bodies mirror the canonical sources of truth checked into
//! the repo-root `migrations/` tree (`000_lazuli_audit.sql`,
//! `002_create_lazuli_outbox.sql`, `003_create_lazuli_inbox.sql`) so a pilot
//! regenerating produces byte-identical schema. The doctor rule
//! `RUNTIME-EMITTED-TABLE-MIGRATION-001` is the guardrail that fires if any
//! of these go missing from a pilot's `dist/go/migrations/`.

use lazuli_ir::Module;

use crate::GeneratedFile;

const LAZULI_AUDIT_PATH: &str = "migrations/000_lazuli_audit.sql";
const LAZULI_AUDIT_DOWN_PATH: &str = "migrations/000_lazuli_audit.down.sql";
const LAZULI_OUTBOX_PATH: &str = "migrations/000_lazuli_outbox.sql";
const LAZULI_OUTBOX_DOWN_PATH: &str = "migrations/000_lazuli_outbox.down.sql";
const LAZULI_INBOX_PATH: &str = "migrations/000_lazuli_inbox.sql";
const LAZULI_INBOX_DOWN_PATH: &str = "migrations/000_lazuli_inbox.down.sql";

const LAZULI_AUDIT_DDL: &str = "\
-- Code generated by lazuli; DO NOT EDIT.
-- source: lazuli core (SEC-C2 transactional audit trail)
CREATE TABLE IF NOT EXISTS lazuli_audit (
    id BIGSERIAL PRIMARY KEY,
    command TEXT NOT NULL,
    actor TEXT NOT NULL,
    tenant TEXT,
    decision TEXT NOT NULL,
    fields JSONB,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lazuli_audit_recorded_at_idx ON lazuli_audit (recorded_at DESC);
CREATE INDEX IF NOT EXISTS lazuli_audit_actor_idx ON lazuli_audit (actor);
";

const LAZULI_OUTBOX_DDL: &str = "\
-- Code generated by lazuli; DO NOT EDIT.
-- source: lazuli core (EVENT-OUTBOX §3.3 transactional outbox)
CREATE TABLE IF NOT EXISTS lazuli_outbox (
    id             BIGSERIAL    PRIMARY KEY,
    envelope_id    TEXT         NOT NULL,
    event_name     TEXT         NOT NULL,
    payload        JSONB        NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    dispatched_at  TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS lazuli_outbox_undispatched_idx
    ON lazuli_outbox (dispatched_at)
    WHERE dispatched_at IS NULL;
";

const LAZULI_INBOX_DDL: &str = "\
-- Code generated by lazuli; DO NOT EDIT.
-- source: lazuli core (EVENT-OUTBOX §3.3 receiver-side idempotency)
CREATE TABLE IF NOT EXISTS lazuli_inbox (
    envelope_id    TEXT         PRIMARY KEY,
    event_name     TEXT         NOT NULL,
    seen_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);
";

fn down(table: &str) -> String {
    format!(
        "-- Code generated by lazuli; DO NOT EDIT.\n-- rollback for {table}\n\nDROP TABLE IF EXISTS {table};\n"
    )
}

/// `true` when any command in the module declares `audit ...` — the
/// activation predicate for `lazuli_audit`.
fn any_command_audits(module: &Module) -> bool {
    module
        .features
        .iter()
        .flat_map(|f| f.commands.iter())
        .any(|c| c.audit.is_some())
}

/// `true` when any event (standalone or under an event group) opts into the
/// transactional outbox — the activation predicate for
/// `lazuli_outbox` / `lazuli_inbox`. Mirrors `command::build_outbox_index`.
fn any_guaranteed_outbox(module: &Module) -> bool {
    module.features.iter().any(|f| {
        f.events.iter().any(|e| e.outbox.is_guaranteed())
            || f.event_groups.iter().any(|g| {
                g.events_outbox.iter().any(|m| m.is_guaranteed())
                    || g.variants.iter().any(|v| v.outbox.is_guaranteed())
            })
    })
}

/// Emit the framework-synthesized table migrations whose runtime path the
/// module's IR activates. `audit_log` is NOT emitted here — it stays
/// unconditional via [`super::audit::emit_audit_log_ddl`].
///
/// ## Examples
///
/// ```ignore
/// let files = emit_framework_table_migrations(&module);
/// // Empty when the module neither audits nor uses a guaranteed outbox.
/// ```
pub fn emit_framework_table_migrations(module: &Module) -> Vec<GeneratedFile> {
    let mut files = Vec::new();

    if any_command_audits(module) {
        files.push(GeneratedFile {
            path: LAZULI_AUDIT_PATH.to_owned(),
            contents: LAZULI_AUDIT_DDL.to_owned(),
        });
        files.push(GeneratedFile {
            path: LAZULI_AUDIT_DOWN_PATH.to_owned(),
            contents: down("lazuli_audit"),
        });
    }

    if any_guaranteed_outbox(module) {
        files.push(GeneratedFile {
            path: LAZULI_OUTBOX_PATH.to_owned(),
            contents: LAZULI_OUTBOX_DDL.to_owned(),
        });
        files.push(GeneratedFile {
            path: LAZULI_OUTBOX_DOWN_PATH.to_owned(),
            contents: down("lazuli_outbox"),
        });
        files.push(GeneratedFile {
            path: LAZULI_INBOX_PATH.to_owned(),
            contents: LAZULI_INBOX_DDL.to_owned(),
        });
        files.push(GeneratedFile {
            path: LAZULI_INBOX_DOWN_PATH.to_owned(),
            contents: down("lazuli_inbox"),
        });
    }

    files
}


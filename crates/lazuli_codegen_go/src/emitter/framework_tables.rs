    #[test]
    fn empty_module_emits_nothing() {
        let files = emit_framework_table_migrations(&base_module(vec![base_feature("customer")]));
        assert!(files.is_empty(), "{files:?}");
    }

    #[test]
    fn audit_command_emits_lazuli_audit_up_and_down() {
        let mut feature = base_feature("account");
        let mut cmd = base_command("create");
        cmd.audit = Some(audit_default());
        feature.commands.push(cmd);

        let files = emit_framework_table_migrations(&base_module(vec![feature]));
        let up = files
            .iter()
            .find(|f| f.path == LAZULI_AUDIT_PATH)
            .expect("lazuli_audit up migration");
        assert!(up.contents.contains("CREATE TABLE IF NOT EXISTS lazuli_audit ("));
        assert!(files.iter().any(|f| f.path == LAZULI_AUDIT_DOWN_PATH
            && f.contents.contains("DROP TABLE IF EXISTS lazuli_audit;")));
        // No outbox usage → no outbox/inbox files.
        assert!(!files.iter().any(|f| f.path == LAZULI_OUTBOX_PATH));
    }

    #[test]
    fn guaranteed_outbox_emits_outbox_and_inbox() {
        let mut feature = base_feature("billing");
        feature
            .events
            .push(base_event("InvoicePaid", OutboxMode::Guaranteed));

        let files = emit_framework_table_migrations(&base_module(vec![feature]));
        assert!(files.iter().any(|f| f.path == LAZULI_OUTBOX_PATH
            && f.contents.contains("CREATE TABLE IF NOT EXISTS lazuli_outbox (")));
        assert!(files.iter().any(|f| f.path == LAZULI_INBOX_PATH
            && f.contents.contains("CREATE TABLE IF NOT EXISTS lazuli_inbox (")));
        // No audit usage → no lazuli_audit file.
        assert!(!files.iter().any(|f| f.path == LAZULI_AUDIT_PATH));
    }

    #[test]
    fn non_guaranteed_outbox_emits_nothing() {
        let mut feature = base_feature("catalog");
        feature
            .events
            .push(base_event("Listed", OutboxMode::None));
        let files = emit_framework_table_migrations(&base_module(vec![feature]));
        assert!(files.is_empty(), "{files:?}");
    }

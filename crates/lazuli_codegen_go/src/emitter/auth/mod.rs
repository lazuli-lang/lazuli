use format::{escape_route_segment, escape_string, pascal_case, write_aligned_kv_rows, write_section_banner};

/// Emit `<feature>/auth.gen.go` for a feature, or `None` when the
/// feature declares no auth block.
pub fn emit_auth_file(
    source_label: &str,
    feature: &Feature,
    module_name: &str,
    cross_index: &CrossFeatureIndex<'_>,
    emit_ctx: &EmitContext<'_>,
) -> Option<String> {
    let auth = feature.auth.as_ref()?;

    // The signature mirrors the other per-kind emitters. Auth contracts
    // carry string references rather than typed field refs, so this
    // slice does not need cross-feature type resolution today.
    let _ = (module_name, cross_index);

    let mut p = GoPrinter::new();
    let mut imports = ImportSet::new();
    imports.add("lazuli.dev/runtime/lazuli/auth");
    if has_auth_routes(auth) {
        imports.add("context");
        imports.add("lazuli.dev/runtime/lazuli");
    }
    if auth.sessions.is_some() {
        imports.add("time");
    }

    p.banner(
        source_label,
        &super::casing::gen_package_name(&feature.name),
    );
    imports.emit(&mut p);
    p.blank();

    emit_auth(&mut p, feature, auth, emit_ctx);

    Some(p.finish())
}

fn emit_auth(p: &mut GoPrinter, feature: &Feature, auth_block: &Auth, emit_ctx: &EmitContext<'_>) {
    // Auth contract vars are PascalCase so cross-package handlers in
    // `<feature>handlers` can reference them via `<feature>gen.AuthPassword`,
    // `<feature>gen.AuthSessions`, etc. (Go exports start with an uppercase
    // first letter.)
    let feature_pascal = pascal_case(&feature.name);
    let identity_var = format!("{feature_pascal}AuthIdentity");

    write_section_banner(
        p,
        &[
            format!("Auth: {}", feature.name),
            "  auth identity/password/sessions/mfa/oauth".to_owned(),
        ],
    );

    emit_pattern_header(p, PATTERN_AUTH_LOGIN);
    let line_directive_emitted = emit_ctx.emit_line_directive(p, auth_block.span_ref);
    emit_identity(p, &identity_var, auth_block);

    if let Some(password) = &auth_block.password {
        p.blank();
        emit_password(p, &feature_pascal, &identity_var, password);
    }

    if let Some(sessions) = &auth_block.sessions {
        p.blank();
        emit_sessions(p, &feature_pascal, sessions);
    }

    let mut oauth: Vec<&AuthOAuthProvider> = auth_block.oauth.iter().collect();
    oauth.sort_by(|a, b| {
        a.provider
            .cmp(&b.provider)
            .then_with(|| a.adapter.cmp(&b.adapter))
    });
    for provider in oauth {
        p.blank();
        emit_oauth(p, &feature_pascal, provider);
    }

    if let Some(mfa) = &auth_block.mfa {
        p.blank();
        emit_mfa(p, &feature_pascal, mfa);
    }

    let routes = auth_routes(auth_block);
    if !routes.is_empty() {
        p.blank();
        emit_auth_routes(p, feature, &routes, emit_ctx);
    }
    if auth_block.sessions.is_some() {
        p.blank();
        emit_session_resolver_register(
            p,
            feature,
            &feature_pascal,
            auth_block.sessions.as_ref().unwrap(),
        );
    }
    emit_ctx.reset_line_directive(p, line_directive_emitted);
}

/// Emit an `init()` block that registers the feature's
/// `auth.sessions` contract with the runtime session resolver.
/// Wires the production session middleware to this feature's table
/// so `Authorization: Bearer <token>` and the `lazuli_session`
/// cookie populate `Ctx.User` automatically.
fn emit_session_resolver_register(
    p: &mut GoPrinter,
    feature: &Feature,
    feature_pascal: &str,
    sessions: &AuthSessions,
) {
    write_section_banner(
        p,
        &[
            format!("Auth session resolver: {}", feature.name),
            "  wires the production session middleware to this feature".to_owned(),
        ],
    );
    let pattern = if sessions.is_rotation_enabled() {
        PATTERN_AUTH_REFRESH
    } else {
        PATTERN_AUTH_LOGIN
    };
    emit_pattern_header(p, pattern);
    p.line("func init() {");
    p.indent();
    p.line(&format!(
        "auth.RegisterSessionContract({feature_pascal}AuthSessions)"
    ));
    if sessions.is_rotation_enabled() {
        p.line(&format!(
            "auth.RegisterRefreshContract({feature_pascal}AuthSessions)"
        ));
    }
    p.dedent();
    p.line("}");
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct AuthRoute {
    name_suffix: String,
    method: &'static str,
    path: String,
    handler: &'static str,
    verify_handler_name: bool,
}

fn has_auth_routes(auth_block: &Auth) -> bool {
    auth_block.password.is_some() || auth_block.sessions.is_some() || !auth_block.oauth.is_empty()
}

fn auth_routes(auth_block: &Auth) -> Vec<AuthRoute> {
    let mut routes = Vec::new();

    if auth_block.password.is_some() {
        routes.push(AuthRoute {
            name_suffix: "login".to_owned(),
            method: "lazuli.MethodPost",
            path: "/auth/login".to_owned(),
            handler: "auth.LoginHandler",
            verify_handler_name: false,
        });
        routes.push(AuthRoute {
            name_suffix: "signup".to_owned(),
            method: "lazuli.MethodPost",
            path: "/auth/signup".to_owned(),
            handler: "auth.SignupHandler",
            verify_handler_name: false,
        });
    }

    if auth_block.password.is_some() || auth_block.sessions.is_some() {
        routes.push(AuthRoute {
            name_suffix: "logout".to_owned(),
            method: "lazuli.MethodPost",
            path: "/auth/logout".to_owned(),
            handler: "auth.LogoutHandler",
            verify_handler_name: false,
        });
    }

    let mut oauth: Vec<&AuthOAuthProvider> = auth_block.oauth.iter().collect();
    oauth.sort_by(|a, b| {
        a.provider
            .cmp(&b.provider)
            .then_with(|| a.adapter.cmp(&b.adapter))
    });
    for provider in oauth {
        let provider_path = escape_route_segment(&provider.provider);
        routes.push(AuthRoute {
            name_suffix: format!("oauth.{}", provider.provider),
            method: "lazuli.MethodGet",
            path: format!("/auth/oauth/{provider_path}"),
            handler: "auth.OAuthHandler",
            verify_handler_name: true,
        });
        routes.push(AuthRoute {
            name_suffix: format!("oauth.{}.callback", provider.provider),
            method: "lazuli.MethodGet",
            path: format!("/auth/oauth/{provider_path}/callback"),
            handler: "auth.OAuthCallbackHandler",
            verify_handler_name: true,
        });
    }

    routes
}

fn emit_auth_routes(
    p: &mut GoPrinter,
    feature: &Feature,
    routes: &[AuthRoute],
    emit_ctx: &EmitContext<'_>,
) {
    write_section_banner(
        p,
        &[
            format!("Auth HTTP routes: {}", feature.name),
            "  canonical auth auto-mounts".to_owned(),
        ],
    );
    emit_pattern_header(p, PATTERN_AUTH_LOGIN);
    p.line("func init() {");
    p.indent();
    for route in routes {
        if route.verify_handler_name {
            p.line("// TODO(runtime): handler name verification");
        }
        p.line("lazuli.RegisterApi(&lazuli.Api[any, any]{");
        p.indent();
        write_aligned_kv_rows(
            p,
            &[
                (
                    "Name:".to_owned(),
                    format!(
                        "\"{}.auth.{}\",",
                        escape_string(&feature.name),
                        escape_string(&route.name_suffix)
                    ),
                ),
                (
                    "Feature:".to_owned(),
                    format!("\"{}\",", escape_string(&feature.name)),
                ),
                ("Method:".to_owned(), format!("{},", route.method)),
                (
                    "Path:".to_owned(),
                    format!("\"{}\",", escape_string(&route.path)),
                ),
                ("Handler:".to_owned(), format!("{},", route.handler)),
            ],
        );
        emit_ctx.emit_with_source_field(p, "auth", &route.name_suffix, None);
        p.dedent();
        p.line("})");
    }
    p.dedent();
    p.line("}");
}


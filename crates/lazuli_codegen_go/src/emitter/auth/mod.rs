//! Cell G1 - `Auth` kind emission. Walks the single auth block declared
//! on a feature and emits the lowered Lazuli Go auth contracts into
//! `<feature>/auth.gen.go`.
//!
//! Proposal references:
//! - Section 3.5 - Auth declaration shape.
//! - Section 11 - runtime boundary discipline. The only runtime package
//!   referenced here is `lazuli.dev/runtime/lazuli/auth`; session TTLs
//!   additionally use stdlib `time` because the current Lazuli Go
//!   `SessionsContract.TTL` field is `time.Duration`.
//!
//! Determinism: there is at most one identity/password/sessions/mfa
//! block, and OAuth providers are sorted by provider then adapter before
//! emission so `oauth: Vec<_>` order cannot perturb generated bytes.

